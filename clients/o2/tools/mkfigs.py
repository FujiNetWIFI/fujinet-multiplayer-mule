#!/usr/bin/env python3
"""mkfigs.py -- the species' figures for the O2's sprites (src/figs.inc).

    mkfigs.py [MAPSPR [OUT]]

From the 2600 client's map figures (clients/atari-2600/build/gen/mapspr.inc,
made by its tools/mkgfx2600.py from the Atari disk: species * 56 + frame * 8,
frame 2 standing, 0 and 1 walking right; bit 7 the leftmost dot, row 0
blank). The
O2's sprite wants bit 0 the leftmost dot, and 7 rows (one character band):
rows 1-7, then a blank. Run it again only if those figures change; figs.inc
is checked in, so the O2's build does not need the 2600's.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = ["MECHTRON", "GOLLUMER", "PACKER", "BONZOID",
         "SPHEROID", "FLAPPER", "LEGGITE", "HUMANOID"]


def rev(b):
    return int("{:08b}".format(b)[::-1], 2)


def main(src=None, out=None):
    src = src or os.path.join(HERE, "..", "..", "atari-2600", "build", "gen", "mapspr.inc")
    out = out or os.path.join(HERE, "..", "src", "figs.inc")
    data = []
    on = False
    for line in open(src):
        if re.match(r"\w+:", line):
            on = line.startswith("MFIGS:")     # (then the M.U.L.E. and the wampus)
        m = re.match(r"\s*DB\s+(.*)", line, re.I)
        if m and on:
            data += [int(x.strip().lstrip("$"), 16) for x in m.group(1).split(",")]
    assert len(data) == 8 * 56, len(data)

    def fig(sp, fr):
        rows = data[sp * 56 + fr * 8:sp * 56 + fr * 8 + 8]
        return [rev(b) for b in rows[1:8]] + [0]

    with open(out, "w") as f:
        f.write("; figs.inc -- GENERATED by tools/mkfigs.py from the 2600 client's map\n")
        f.write("; figures -- do not edit. 8 bytes a figure (7 rows, a blank), by\n")
        f.write("; species; bit 0 the leftmost dot. FIGS_STAND standing, FIGS_WALK0 and\n")
        f.write("; FIGS_WALK1 walking by turns.\n\n")
        for name, fr in (("FIGS_STAND", 2), ("FIGS_WALK0", 0), ("FIGS_WALK1", 1)):
            f.write("%s macro\n" % name)
            for sp in range(8):
                f.write("    db %s ; %s\n" % (", ".join("%03Xh" % b for b in fig(sp, fr)), NAMES[sp]))
            f.write("    endm\n")
    print(out)


if __name__ == "__main__":
    main(*sys.argv[1:3])
