#!/usr/bin/env python3
"""mkproto.py -- AS equates from clients/mule_proto.h.

    mkproto.py ../mule_proto.h build/proto.inc

Every #define becomes an equate, every struct a set of field offsets named
<STRUCT>_<FIELD> (MuleHeader -> HDR_PHASE, MulePlayer -> PL_MONEY, ...) plus
<STRUCT>_SIZE, and MuleState's members their offsets in the 550-byte state
(ST_PLAYERS, ST_MAP, ...). The layout is computed, never copied, so a server
change that moves a field breaks the build instead of the game.
"""
import re
import sys

SIZES = {"uint8_t": 1, "int8_t": 1, "char": 1, "uint16_t": 2, "int16_t": 2,
         "uint32_t": 4, "int32_t": 4}
PREFIX = {"MuleHeader": "HDR", "MulePlayer": "PL", "MuleMap": "MAP",
          "MuleStore": "STO", "MuleGrant": "GR", "MuleAuction": "AU",
          "MuleWampus": "WP", "MuleTurn": "TU", "MuleColony": "CO",
          "MuleState": "ST", "MuleTable": "TBL"}


def main(src, out):
    text = open(src).read()
    lines = ["; GENERATED by tools/mkproto.py from mule_proto.h -- do not edit."]
    for name, val in re.findall(r"^#define (\w+) ('.'|-?\d+|0x[0-9A-Fa-f]+)\s*$", text, re.M):
        if name in ("MULE_PROTO_H",):
            continue
        if val.startswith("0x"):
            val = "0%sh" % val[2:].upper()
        lines.append("%-24s equ %s" % (name, val))

    sizes = dict(SIZES)
    for body, sname in re.findall(r"typedef struct \{[^\n]*\n(.*?)\} (\w+);", text, re.S):
        pre = PREFIX[sname]
        off = 0
        for ftype, fname, count in re.findall(r"^\s*(\w+) (\w+)(?:\[(\d+)\])?;", body, re.M):
            n = int(count) if count else 1
            lines.append("%-24s equ %d" % ("%s_%s" % (pre, fname.upper()), off))
            off += sizes[ftype] * n
        sizes[sname] = off
        lines.append("%-24s equ %d" % ("%s_SIZE" % pre, off))
    assert sizes["MuleState"] == 550, sizes["MuleState"]
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
