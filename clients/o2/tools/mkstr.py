#!/usr/bin/env python3
"""mkstr.py -- the strings pages: src/strings.txt into AS includes.

usage: mkstr.py strings.txt OUTDIR

strings.txt: `NAME text` a line, '#' a comment, `@bank` a new bank (a group
whose ids must run on, like the ratings). A text line is 16
characters: '|' breaks a string's lines, otherwise its words wrap ('%', a
number, counts as 5; in a title, T_*, it is the round: 2; in a player
event, E_*, an amount under $10000: 4). An empty text is
a string with one blank line. Only the font's characters: no ! , ' # or
lowercase.

Strings are numbered in file order; a bank holds what its four data pages
take (63 at most): bank k's are 64k+1 .. (pstr.inc; the main loop farcalls
the bank's page, p2.inc str_pages).

Output (never committed):
  OUTDIR/strid.inc      S_NAME equ id, and STR_BANKS
  OUTDIR/strdirK.inc    bank K's directory, for page $8: sdir, the first
                        local id in each data page, $FF after the last
  OUTDIR/strdatK.inc    bank K's data pages, $A00-$DFF. Each starts with
                        its read stub (MOVP A,@A / RET), then the offsets
                        of its strings, then the strings: a line ends in 0,
                        a string's last line in 1.
"""
import os
import sys

WIDTH = 16
NUMW = 5
FONT = "0123456789:$ ?LPWERTUIOQSDFGHJKAZXCVBM.-=YN/+%"   # mkcharmap.py ROM
                                    # ('%' the number; its * % # are x / and a block)


def cols(s, numw=NUMW):
    return len(s) + (numw - 1) * s.count("%")
PAGES = 4           # $A00-$DFF
PER_BANK = 63
BANK_PAGES = [5, 9, 14]     # the code page of each bank (mule.a48, p2.inc str_pages)


def wrap(name, text):
    numw = 2 if name.startswith("T_") else 4 if name.startswith("E_") else NUMW
    if not text:
        return [""]
    out = []
    for part in text.split("|"):
        line, w = "", 0
        for word in part.split(" "):
            ww = cols(word, numw)
            if line and w + 1 + ww > WIDTH:
                out.append(line)
                line, w = "", 0
            line, w = (line + " " + word, w + 1 + ww) if line else (word, ww)
        out.append(line)
    if name[:2] in ("T_", "E_", "W_") and len(out) > 1:
        sys.exit("mkstr.py: %s is one line (T_, E_, W_): '%s'" % (name, text))
    for line in out:
        if cols(line, numw) > WIDTH:
            sys.exit("mkstr.py: %s: '%s' is over %d columns" % (name, line, WIDTH))
    return out


def encode(lines):
    b = bytearray()
    for i, line in enumerate(lines):
        for c in line:
            if c not in FONT:
                sys.exit("mkstr.py: %r has no glyph" % c)
        b += line.encode("ascii")
        b.append(1 if i == len(lines) - 1 else 0)
    return bytes(b)


def main():
    src, out = sys.argv[1], sys.argv[2]
    strings = []
    for n, raw in enumerate(open(src), 1):
        raw = raw.rstrip("\n")
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if raw.strip() == "@bank":
            strings.append(("@bank", ""))
            continue
        name, _, text = raw.partition(" ")
        strings.append((name, text.strip()))
    names = [s[0] for s in strings if s[0] != "@bank"]
    if len(set(names)) != len(names):
        sys.exit("mkstr.py: a name twice")

    # Banks fill in file order: a string goes on the current data page,
    # the next page, or the next bank's first.
    banks = [[[]]]             # bank -> pages -> (local id, name, bytes)
    ids = []
    for name, text in strings:
        if name == "@bank":
            if banks[-1] != [[]]:
                banks.append([[]])
            continue
        data = encode(wrap(name, text))
        pages = banks[-1]
        local = sum(len(p) for p in pages) + 1
        cur = pages[-1]
        size = 2 + len(cur) + 1 + sum(len(d) for _, _, d in cur) + len(data)
        if size > 256 or local > PER_BANK:
            if len(pages) == PAGES or local > PER_BANK:
                banks.append([[]])
                local = 1
            else:
                pages.append([])
        k = len(banks) - 1
        ids.append((name, 64 * k + local))
        banks[-1][-1].append((local, name, data))
    if len(banks) > len(BANK_PAGES):
        sys.exit("mkstr.py: %d banks, pstr.inc's pages hold %d" % (len(banks), len(BANK_PAGES)))
    for k, pages in enumerate(banks):

        with open(os.path.join(out, "strdir%d.inc" % k), "w") as f:
            f.write("; GENERATED by tools/mkstr.py -- do not edit.\n")
            firsts = [p[0][0] for p in pages] + [0xFF]
            f.write("sdir: db %s\n" % ", ".join("%d" % x for x in firsts))
        with open(os.path.join(out, "strdat%d.inc" % k), "w") as f:
            f.write("; GENERATED by tools/mkstr.py -- do not edit.\n")
            for i, page in enumerate(pages):
                f.write("\n    org 0%X00h\nsdat%d:\n    movp a,@a\n    ret\n" % (0xA + i, i))
                off = 2 + len(page)
                offs = []
                for _, _, d in page:
                    offs.append(off)
                    off += len(d)
                f.write("    db %s\n" % ", ".join("%d" % o for o in offs))
                for local, name, d in page:
                    f.write("    db %s  ; %s\n" % (", ".join("%d" % c for c in d), name))
    with open(os.path.join(out, "strid.inc"), "w") as f:
        f.write("; GENERATED by tools/mkstr.py -- do not edit.\n")
        f.write("STR_BANKS equ %d\n" % len(banks))
        for name, i in ids:
            f.write("%-12s equ %d\n" % (name, i))


if __name__ == "__main__":
    main()
