#!/bin/bash
# build.sh -- M.U.L.E. for the Odyssey 2: build/mule.bin, a protocol 2
# (APPBANK) image -- the fixed half ($400-$7FF) and NPAGES pages of 2K.
#
#   ./build.sh                 the image
#   ENDPOINT=http://host:port ./build.sh
#
# Needs Macroassembler AS (~/asl/asl and p2bin, or ASL=/P2BIN=).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="${OUT:-$HERE/build}"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
NPAGES=16
mkdir -p "$OUT"

python3 "$HERE/tools/checkflags.py" "$HERE"/src/*.inc
python3 "$HERE/tools/mkproto.py" "$HERE/../mule_proto.h" "$OUT/proto.inc"
python3 "$HERE/tools/mkcharmap.py" "$OUT/charmap.inc"
python3 "$HERE/tools/mkstr.py" "$HERE/src/strings.txt" "$OUT"
# The server, unless the lobby's room appkey names one. No trailing '/': the
# routes start with one.
ENDPOINT="${ENDPOINT:-http://fujinet.online:9900}"
printf '; GENERATED by build.sh -- do not edit.\nu_endp: db "%s",0\n' "$ENDPOINT" > "$OUT/endpoint.inc"
cp "$HERE"/src/*.inc "$HERE/g7000.h" "$HERE/mule.a48" "$OUT/"

parts=""
for p in $(seq 0 $((NPAGES-1))); do
  printf '; GENERATED by build.sh -- do not edit.\nPAGE equ %d\nNPAGES equ %d\n    include "mule.a48"\n' \
    "$p" "$NPAGES" > "$OUT/mule_p$p.a48"
  ( cd "$OUT" && "$ASL" -q -L -U "mule_p$p.a48" \
      && "$P2BIN" "mule_p$p.p" "mule_pg$p.bin" -r 0x800-0xFFF -l 0 >/dev/null \
      && "$P2BIN" "mule_p$p.p" "mule_fx$p.bin" -r 0x400-0x7FF -l 0 >/dev/null )
  python3 "$HERE/tools/checkobj.py" "$OUT/mule_p$p.p"
  python3 "$HERE/tools/checklayout.py" "$OUT/mule_p$p.lst"
  python3 "$HERE/tools/checkmb.py" "$OUT/mule_p$p.lst" >/dev/null
  python3 "$HERE/tools/checkpage.py" "$OUT/mule_p$p.lst"
  # Every page carries the fixed half; they have to be the same bytes.
  cmp -s "$OUT/mule_fx0.bin" "$OUT/mule_fx$p.bin" \
    || { echo "build.sh: page $p assembled a different fixed half" >&2; exit 1; }
  parts="$parts $OUT/mule_pg$p.bin"
done
# The stack is 8 levels and wraps silently: interrupts plus the deepest main
# chain have to fit.
python3 "$HERE/tools/checkstack.py" $(for p in $(seq 0 $((NPAGES-1))); do echo "$OUT/mule_p$p.lst"; done) >/dev/null
cat "$OUT/mule_fx0.bin" $parts > "$OUT/mule.bin"
size=$(wc -c < "$OUT/mule.bin")
[ "$size" -eq $((1024 + 2048 * NPAGES)) ] \
  || { echo "build.sh: mule.bin is $size bytes" >&2; exit 1; }
echo "build/mule.bin: $size bytes, $NPAGES pages"
