#!/usr/bin/env python3
"""gen.py -- the M0 probe's data (tools/a78sim/probe): per-zone display
lists and DLI tables as ca65 source, and the same layout as JSON for
check.py.

    gen.py out.s out.json

24 zones, each one solid colour of its own in a KIND of object:
  T  320A, 1-byte chars, CB $40, glyph $FF   colour 2 of pair A
  D  160A, 1-byte chars, CB $48, glyph $55   colour 1
  M  160A, 2-byte chars, CB $50, glyph $AA   colour 2
  B  160A, 1-byte chars, CB $48, glyph $FF   colour 3
Even zones use P0/P1, odd ones P2/P3. PAD transparent direct objects (12
bytes, 44 DMA cycles each) load the zone, so the zone before each switch has
a DMA count of its own; the sprite (P4, white) runs down every zone at x 140.
"""
import json
import sys

KINDS = "TDTMTDDTMMTBTDMTDTMBTDTM"
PADS = [0, 0, 1, 0, 2, 0, 3, 0, 3, 0, 3, 1, 3, 2, 3, 0, 3, 1, 2, 3, 3, 0, 3, 3]
COLOURS = [0x34, 0xC4, 0x84, 0x1C, 0x54, 0x94, 0x24, 0xD8, 0x46, 0xA6, 0x66, 0xE6,
           0x36, 0xB6, 0x56, 0xF8, 0x26, 0x76, 0xC8, 0x18, 0x88, 0x48, 0xE8, 0x96]
K = {  # cb, ctrl, map row, codes, colour index (0-based in pair A), bytes per code
    "T": (0x40, 0x4B, 0x5800, 20, 1, 1),
    "D": (0x48, 0x48, 0x5800, 20, 0, 1),
    "M": (0x50, 0x58, 0x5900, 10, 1, 2),
    "B": (0x48, 0x48, 0x5A00, 20, 2, 1),
}
PAD_W = 12
DLBASE = 0x1800


def main():
    out_s, out_j = sys.argv[1], sys.argv[2]
    zones = []
    for z, k in enumerate(KINDS):
        cb, ctrl, mp, n, ci, bpc = K[k]
        pa = 0 if z % 2 == 0 else 2           # pair A's palette
        dl = [mp & 0xFF, 0x60, mp >> 8, (pa << 5) | ((-n) & 0x1F), 0]
        cyc = 10 + n * (6 if bpc == 1 else 9)
        for _ in range(PADS[z]):
            dl += [0x10, (5 << 5) | ((-PAD_W) & 0x1F), 0x60, 60]
            cyc += 8 + 3 * PAD_W
        dl += [0x00, (4 << 5) | ((-2) & 0x1F), 0x60, 140]
        cyc += 14
        dl += [0, 0]
        assert len(dl) <= 64
        # pair A then B: (C1, C2, C3) each; the zone's colour in one of A's
        pal = [0] * 6
        pal[ci] = COLOURS[z]
        base = 0x21 if z % 2 == 0 else 0x29
        regs = [base, base + 1, base + 2, base + 4, base + 5, base + 6]
        prev = KINDS[z - 1] if z else k
        rm = ctrl & 3
        prm = K[prev][1] & 3
        late = rm == 3 and prm == 0              # 160A -> 320A: switch at raster C
        early_ctrl = ctrl if not late else (ctrl & ~3) | prm
        if late:
            writes = [(regs[1], pal[1])]         # the text colour only
        else:
            writes = list(zip(regs, pal))
        zones.append(dict(kind=k, cb=cb, ca=early_ctrl, cb2=ctrl, late=late, writes=writes, pal=pal,
                          dl=dl, dma=16 + cyc + 6 + 17, colour=COLOURS[z], ci=ci))
    # the bottom zone (24): as zone 23, no colours
    last = zones[-1]
    zones.append(dict(kind="-", cb=0x40, ca=last["cb2"], cb2=last["cb2"], late=False,
                      writes=[], pal=[0] * 6, dl=[0, 0], dma=0, colour=0, ci=0))

    s = ["; probe_data.s -- GENERATED by gen.py", '        .segment "RODATA"',
         "        .export z_cb, z_ca, z_cb2, z_f, dl_rom",
         "        .export " + ", ".join("z_pal%d" % i for i in range(6))]
    s.append("z_cb:   .byte " + ",".join("$%02X" % z["cb"] for z in zones))
    s.append("z_ca:   .byte " + ",".join("$%02X" % z["ca"] for z in zones))
    s.append("z_cb2:  .byte " + ",".join("$%02X" % z["cb2"] for z in zones))
    # flags: bit 7 the late switch, bit 6 the odd pair (P2/P3), bit 5 no colours
    s.append("z_f:    .byte " + ",".join("$%02X" % ((0x80 if z["late"] else 0) | (0x40 if i % 2 else 0) |
                                                    (0x20 if not z["writes"] else 0))
                                         for i, z in enumerate(zones)))
    for i in range(6):
        s.append("z_pal%d: .byte " % i + ",".join(
            "$%02X" % (z["pal"][i] if z["writes"] else 0) for z in zones))
    s.append("dl_rom:")
    for z in zones[:24]:
        d = z["dl"] + [0] * (64 - len(z["dl"]))
        for i in range(0, 64, 16):
            s.append("        .byte " + ",".join("$%02X" % b for b in d[i:i + 16]))
    open(out_s, "w").write("\n".join(s) + "\n")
    json.dump(dict(zones=zones[:24], nz=len(zones)), open(out_j, "w"), indent=1)


if __name__ == "__main__":
    main()
