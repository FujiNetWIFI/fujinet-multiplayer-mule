#!/usr/bin/env python3
"""Build the Atari client's sounds (gen/atari/snd.s) from the original disk.

usage: mksnd_atari.py [--atr "M.U.L.E. (1983)(Electronic Arts)(US).atr"] out.s

The tunes (the title theme from the boot image, the round's tune from the
main image), their pitch tables, the voice-4 effect tables, the species'
footsteps and the player-event jingles are copied from the original (CRC32
F76D2896); they belong to their copyright holders, and the generated file
must not be committed. The longer effects are scripts for src/atari/pokey.s
written from how the original plays them (addresses in the comments are in
its loaded images). Without --atr the copied parts are silent stand-ins.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "intv", "tools"))
import mkgfx as intv  # noqa: E402  (load_disk)

F1, C1, F2, C2, F3, C3, F4, C4, CTL = range(9)


# ---- the script language (pokey.s) ------------------------------------------
def SET(r, v):
    return [0x80 + r, v & 255]


def W(n):
    out = []
    while n > 0:
        k = min(n, 127)
        out.append(k)
        n -= k
    return out


def LOOP(n):
    return [0x90, n & 255]


NEXT = [0x91]
END = [0x00]


def ADD(r, d):
    return [0xA0 + r, d & 255]


def RND(r, m, o=0):
    return [0xB0 + r, m, o]


def QUARTER(r, v):
    return [0xC0 + r, v]


def WRND(m):
    return [0xD0, m]


def sets(**kw):
    out = []
    for k, v in kw.items():
        out += SET(globals()[k], v)
    return out


# ---- the effects ($... are the original's routines; see the RE notes) ------
def ship():                 # $7530: the 15 kHz clock, two low tones, 782 frames
    return SET(CTL, 1) + sets(F1=0xF0, F3=0xFF, C1=0xA6, C3=0xA6) + W(782) + END


def jingle(notes, frames):  # $897C/$89A3: pure tones, one table entry each
    out = SET(C1, 0xA4)
    for i, n in enumerate(notes):
        out += SET(F1, n) + W(frames - (1 if i == 0 else 0))
    return out + END


def chirps():               # $4AA2 + voice-4 effect 6: noise falling away
    one = []
    for f, c in ((0x80, 2), (0x40, 4), (0x20, 6), (0x10, 8), (0x08, 0x0A)):
        one += sets(F4=f, C4=c) + W(1)
    return LOOP(12) + one + sets(F4=0, C4=0) + WRND(15) + NEXT + END


def outfit():               # $69D0: poly4 buzz, down 20 steps, up 24, 6 frames each
    return (sets(C4=0xC8, F4=0xFF) + W(6) + LOOP(19) + ADD(F4, -2) + W(6) + NEXT +
            LOOP(24) + ADD(F4, 2) + W(6) + NEXT + W(12) + END)


def pest():                 # $77E2: buzz on voice 2; the bite ($5F up and down)
    buzz = lambda n: LOOP(n) + SET(C2, 4) + W(6) + SET(C2, 0) + W(6) + NEXT
    bite = (sets(C1=0xAA, F1=0x5F) + LOOP(8) + ADD(F1, 0x14) + W(1) + NEXT +
            LOOP(6) + ADD(F1, -0x14) + W(1) + NEXT + SET(C1, 0xA0) + W(1))
    return SET(F2, 0xC0) + buzz(40) + bite + buzz(48) + END


def pirate():               # $751A: two noise voices while the ship is about
    return sets(F1=0xC8, C1=0x06, F3=0x32, C3=0x03) + W(1500) + END


def rain():                 # $79F9: hiss, and a crack one cloud change in four
    return sets(F1=0x16, C1=0x04, F2=0x8E) + LOOP(200) + QUARTER(C2, 0x0E) + W(6) + NEXT + END


def quake():                # $729A: three noise voices fading in 16 steps
    out = sets(F1=0xFF, F2=0xC8, F3=0x96, C1=0x8C, C2=0x8C, C3=0x8C)
    for i, aa in enumerate(range(16, 0, -1)):
        out += sets(C1=0x80 | aa, C2=0x80 | aa >> 1, C3=0x80 | aa >> 2) + W(19 if i == 0 else 20)
    return out + END


def meteor():               # $7D06: whoosh, the fall, the rumble
    out = sets(C1=0x0F, C2=0x0F) + W(1) + sets(C1=0x8E, F1=0x3C) + W(39)
    out += sets(F1=0xB1, F2=0xB1, C1=0x89, C2=0x89)
    out += LOOP(15) + ADD(F1, 2) + ADD(F2, 2) + W(1) + ADD(F1, 1) + ADD(F2, 1) + W(1)
    out += ADD(F1, 2) + ADD(F2, 2) + W(1) + NEXT
    out += sets(F1=0xFE, F2=0xFE)
    for v in range(15, 0, -1):
        out += sets(C1=v, C2=v) + W(10 if v < 15 else 9)
    return out + END


def radiation():            # $7F40: zaps (then the runaway M.U.L.E.)
    zap = LOOP(8) + RND(F1, 0x1F, 1) + SET(C1, 0xEA) + W(1) + SET(C1, 0xE6) + W(1) + NEXT
    return LOOP(7) + zap + sets(F1=0, C1=0) + W(2) + NEXT + END


def fire():                 # $8050: a two-tone siren
    return SET(C1, 0xA4) + LOOP(4) + SET(F1, 0x3C) + W(30) + SET(F1, 0x79) + W(30) + NEXT + END


# ---- output ------------------------------------------------------------------
def bytes_line(vals, per=16):
    return "\n".join("        .byte   " + ",".join("$%02X" % v for v in vals[i:i + per])
                     for i in range(0, len(vals), per))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--atr")
    ap.add_argument("out")
    a = ap.parse_args()
    if a.atr:
        main_img, boot = intv.load_disk(a.atr)
    else:
        main_img, boot = bytearray(0x10000), bytearray(0x10000)
    src = ["; snd.s -- GENERATED by tools/mksnd_atari.py (%s). Do not edit or commit." %
           ("copied from the Atari disk" if a.atr else "STAND-IN: no ATR given, silent tunes")]

    def seg(name):
        src.append('\n        .segment "%s"' % name)

    def label(name, data, export=True):
        if export:
            src.append("        .export _%s" % name)
        src.append("_%s:" % name)
        src.append(bytes_line(data))

    # resident: the voice-4 effects, footsteps, the short scripts
    seg("RODATA")
    label("v4_tab", list(main_img[0x5E28:0x5E3D]))            # pitch, length, volume x 7
    label("step_tab", list(boot[0x83FB:0x840B]))              # AUDF x 8 species, AUDC x 8

    # the develop overlay: the player events' jingles, outfitting
    seg("OVERLAY5")
    good = list(main_img[0x89CA:0x89D3])[::-1]                # played from the end
    bad = list(main_img[0x89C3:0x89CA])[::-1]
    label("snx_good", jingle(good, 8))
    label("snx_bad", jingle(bad, 20))
    label("snx_outfit", outfit())

    # the status overlay: the tunes (and the ship, for the first round)
    seg("OVERLAY2")
    label("snx_ship2", ship())

    def tune(name, img, base, v1s, v1e, v2s, v2w, v2r, v3s, v3w, v3r, v4s, v4w, v4r,
             params, alt, lo, hi):
        # the tune's data as one block, addresses relative to it
        rel = lambda x: "tune_%s+$%04X" % (name, x - lo)
        src.append("        .export _tune_%s_desc" % name)
        src.append("_tune_%s_desc:" % name)
        src.append("        .word   " + ",".join(rel(x) for x in (v1s, v1e, v2s, v2w, v2r, v3s, v3w, v3r,
                                                                    v4s, v4w, v4r)))
        src.append(bytes_line(params))
        src.append("        .word   pitch1, pitch23")
        src.append("        .byte   %d" % alt)
        src.append("tune_%s:" % name)
        src.append(bytes_line(list(img[lo:hi])))

    # the title theme (boot image, $7C80): voice 1 $7FA8-$80BA then the tune
    # starts over; voices 2-4 loop
    tune("title", boot, 0, 0x7FA8, 0x80BB, 0x80BC, 0x8240, 0x80BC, 0x8241, 0x83B8, 0x8241,
         0x83B9, 0x83C9, 0x83B9, list(boot[0x7C5B:0x7C6B]), 0, 0x7FA8, 0x83CA)
    # the round's tune (main image, $2527): voice 1 from $28B2 for a length
    # that grows with the round (sound.c sets the start and end)
    tune("round", main_img, 0, 0x28B2, 0x28B2, 0x29D3, 0x2B57, 0x29D3, 0x2B58, 0x2CCF, 0x2B58,
         0x2CD0, 0x2CE0, 0x2CD0, list(main_img[0x24A7:0x24AB]) + list(main_img[0x24FE:0x250A]),
         1, 0x28B2, 0x2CE0)
    src.append("        .export _tune_round_len")
    src.append("_tune_round_len:")
    src.append(bytes_line(list(main_img[0x251F:0x2527])))    # 4 words: by round / 4
    src.append("pitch1:")
    src.append(bytes_line(list(main_img[0x24AB:0x24C9])))
    src.append("pitch23:")
    src.append(bytes_line(list(main_img[0x24C9:0x24FA])))

    # the production overlay: the colony events
    seg("OVERLAY3")
    label("snx_ship3", ship())
    label("snx_chirps", chirps())
    for n, f in (("pest", pest), ("pirate", pirate), ("rain", rain), ("quake", quake),
                 ("meteor", meteor), ("radiation", radiation), ("fire", fire)):
        label("snx_" + n, f())

    open(a.out, "w").write("\n".join(src) + "\n")
    print("%s: %s" % (a.out, "Atari sounds" if a.atr else "STAND-IN sounds"))


if __name__ == "__main__":
    main()
