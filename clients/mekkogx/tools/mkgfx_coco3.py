#!/usr/bin/env python3
"""Build the CoCo 3 client's graphics from the Atari disk: gen/coco3/gfx.c
(sprites), art3.c (font, palettes, plot tables, pictures), slide.c (the
ship's slide lists) and town.c.

usage: mkgfx_coco3.py [--atr "M.U.L.E. (1983)(Electronic Arts)(US).atr"] [--preview dir] out.c

Without --atr, stand-in art is used. Never commit the generated files.
The tables are the PCjr's (tools/mkgfx_dos.py): one bit per color clock,
colored when drawn; the town is one nibble (a C_* color) per clock.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mkgfx_hgr as hgr  # noqa: E402
import mkgfx_dos as dos  # noqa: E402

intv = hgr.intv

# C_* (gfx.h) as GIME RGB palette codes, bits R1 G1 B1 R0 G0 B0.
PAL = [0x00, 0x3F, 0x09, 0x29, 0x12, 0x34, 0x24, 0x36,
       0x38, 0x1B, 0x22, 0x35, 0x1D, 0x10, 0x2F, 0x34]
# The same as composite codes (intensity in bits 5-4, hue in 3-0), from XRoar
# 1.11's model of the GIME's composite output; they agree with CONFIG's. The
# four player colors are kept apart before closeness to the RGB colors.
PAL_CMP = [0x00, 0x30, 0x0B, 0x09, 0x11, 0x15, 0x06, 0x23,
           0x20, 0x2D, 0x04, 0x25, 0x1C, 0x01, 0x18, 0x15]
C_BLACK, C_WHITE, C_BLUE, C_PURPLE, C_GREEN, C_ORANGE, C_RED, C_YELLOW = range(8)
C_GREY, C_CYAN, C_BROWN, C_TAN, C_LTBLUE, C_DKGREEN, C_PINK, C_P3 = range(8, 16)

# Atari colors seen in the town -> C_*.
ATARI_TO_C = {0x00: C_BLACK, 0x04: C_GREY, 0x08: C_GREY, 0x0C: C_GREY, 0x0E: C_WHITE,
              0x1A: C_TAN, 0x24: C_BROWN, 0x34: C_ORANGE, 0x44: C_RED, 0x54: C_PURPLE,
              0x84: C_BLUE, 0x86: C_BLUE, 0xB4: C_GREEN, 0xC4: C_GREEN,
              0xD4: C_DKGREEN, 0xF4: C_DKGREEN}


def rgb(code):
    level = (0, 85, 170, 255)
    return (level[((code >> 5) & 1) * 2 + ((code >> 2) & 1)],
            level[((code >> 4) & 1) * 2 + ((code >> 1) & 1)],
            level[((code >> 3) & 1) * 2 + (code & 1)])


def town_nibbles(atari):
    """144 lines of 48 bytes: two clocks a byte, the left in the high nibble."""
    img = dos.town_colours(atari)
    rows = []
    for line in img:
        cols = [dos.lookup(ATARI_TO_C, pix, C_GREY) for pix in line]
        rows.append([cols[idx] << 4 | cols[idx + 1] for idx in range(0, 96, 2)])
    return rows, [[dos.lookup(ATARI_TO_C, pix, C_GREY) for pix in line] for line in img]


def preview(path, town_cols, font, parts):
    try:
        from PIL import Image
    except ImportError:
        return
    pal = [rgb(code) for code in PAL]
    img = Image.new("RGB", (320, 192), pal[C_BLACK])
    for ypos, line in enumerate(town_cols):
        for xpos, col in enumerate(line):
            for half in (0, 1):
                img.putpixel((64 + 2 * xpos + half, 16 + ypos), pal[col])
    for idx, glyph in enumerate(font):
        for ypos, bits in enumerate(glyph):
            for bit in range(8):
                if bits & (0x80 >> bit):
                    img.putpixel(((idx % 40) * 8 + bit, 164 + (idx // 40) * 9 + ypos), pal[C_WHITE])
    img.resize((320 * 2, 192 * 2), Image.NEAREST).save(path)
    img = Image.new("RGB", (len(parts) * 36, 36), pal[C_GREY])
    for num, (name, rows) in enumerate(parts):
        col = (pal[C_LTBLUE] if name == "river" else pal[C_WHITE] if name == "store"
               else pal[C_BLACK] if name.startswith("mount") else pal[C_BLUE])
        for ypos, line in enumerate(rows):
            for xpos, lit in enumerate(line):
                if lit:
                    for half in (0, 1):
                        img.putpixel((num * 36 + 2 + 2 * xpos + half, 2 + ypos), col)
    img.resize((img.width * 2, img.height * 2), Image.NEAREST).save(
        os.path.join(os.path.dirname(path), "plots.png"))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--atr")
    parser.add_argument("--preview")
    parser.add_argument("out")
    args = parser.parse_args()
    atari = hgr.Atari(args.atr) if args.atr else None
    head = ("/* GENERATED by tools/mkgfx_coco3.py (%s). Do not edit or commit. */" %
            ("converted from the Atari disk" if atari else "STAND-IN art: no ATR given"))
    src = [head, "#include <stdint.h>", '#include "../../src/coco/gfxdata3.h"', ""]
    art = list(src)

    art.append("const uint8_t c3_pal[16] = { %s };" % ", ".join("0x%02X" % val for val in PAL))
    art.append("const uint8_t c3_pal_cmp[16] = { %s };" % ", ".join("0x%02X" % val for val in PAL_CMP))

    font = dos.font_dos()
    art.append("const uint8_t c3_font[64 * 8] = {")
    art.append(dos.c_bytes([byte for glyph in font for byte in glyph]))
    art.append("};")

    images = dos.plot_images(atari)
    order = ["border", "icon_house", "icon_food", "icon_energy", "icon_smithore", "icon_crystite",
             "icon_mule", "mount1", "mount2", "mount3", "store", "river"]
    art.append("/* plot parts: 32 lines x 16 color clocks (2 bytes, MSB left) */")
    art.append("const uint8_t plot_parts[%d][64] = {" % len(order))
    for name in order:
        art.append("  { /* %s */" % name)
        art.append(dos.c_bytes([byte for line in images[name] for byte in dos.pack_bits(line, 2)]))
        art.append("  },")
    art.append("};")
    art.append("/* production dots: line, color clock */")
    art.append("const uint8_t plot_dots[8][2] = {")
    art.append("    " + " ".join("{%d,%d}," % dot for dot in dos.plot_dots()))
    art.append("};")

    shapes = dos.shapes(atari)
    src.append("/* sprites: 1 bit a color clock, MSB left */")
    for shape in shapes:
        rowb = (shape.w + 7) // 8
        data = []
        for frame in shape.frames:
            for line in frame:
                data += hgr.pack_row(list(line) + [0] * (rowb * 8 - len(line)))
        src.append("static const uint8_t sh_%s[%d] = {" % (shape.name, len(data)))
        src.append(dos.c_bytes(data))
        src.append("};")
    slide = list(art[:4])
    slide.append("/* a row's changing clocks, bit 7 lit, then 0x7F; the frames in turn */")
    table = []
    for shape in shapes:
        if shape.name not in ("nose", "hull_top", "hull_bot"):
            table.append("0")
            continue
        data = []
        for frame in shape.frames:
            for line in frame:
                prev = 0
                for clock, bit in enumerate(line):
                    if bit != prev:
                        data.append(clock | (0x80 if bit else 0))
                        prev = bit
                data.append(0x7F)
        slide.append("static const uint8_t sl_%s[%d] = {" % (shape.name, len(data)))
        slide.append(dos.c_bytes(data))
        slide.append("};")
        table.append("sl_" + shape.name)
    slide.append("const uint8_t *const c3_slide[%d] = { %s };" % (len(shapes), ", ".join(table)))
    open(os.path.join(os.path.dirname(args.out), "slide.c"), "w").write("\n".join(slide) + "\n")

    src.append("const ShapeDef c3_shapes[%d] = {" % len(shapes))
    for shape in shapes:
        src.append("    { sh_%s, %d, %d, %d }," % (shape.name, (shape.w + 7) // 8, shape.w, shape.h))
    src.append("};")

    art.append("const uint8_t c3_pics[%d][8] = {" % len(hgr.PICS))
    for name, pic in hgr.PICS:
        art.append("    { %s }, /* %s */" % (",".join("0x%02X" % val for line in intv.from_art(pic)
                                                   for val in hgr.pack_row(line)), name))
    art.append("};")
    open(args.out, "w").write("\n".join(src) + "\n")
    open(os.path.join(os.path.dirname(args.out), "art3.c"), "w").write("\n".join(art) + "\n")

    rows, cols = town_nibbles(atari)
    packed = dos.rle([byte for line in rows for byte in line])
    tsrc = [head, "#include <stdint.h>", "",
            "/* the town, 144 lines x 48 bytes a line, a nibble (C_*) a color clock,",
            " * packed: n < 128: n + 1 bytes follow; n >= 128: the next byte n - 125",
            " * times. Its own file: it shares an MMU block with an overlay (bank.c). */",
            "const uint8_t town_rle[%d] = {" % len(packed), dos.c_bytes(packed), "};"]
    open(os.path.join(os.path.dirname(args.out), "town.c"), "w").write("\n".join(tsrc) + "\n")

    if args.preview:
        os.makedirs(args.preview, exist_ok=True)
        preview(os.path.join(args.preview, "town.png"), cols, font,
                [(name, images[name]) for name in order])
    print("%s: %s; town %d bytes packed" %
          (args.out, "Atari graphics" if atari else "STAND-IN art", len(packed)))


if __name__ == "__main__":
    main()
