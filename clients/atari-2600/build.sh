#!/usr/bin/env bash
# build.sh -- assemble the Atari 2600 M.U.L.E. client.
#
#   ./build.sh            build/mule2600.bin, 32768 bytes
#   ./build.sh layout     build/layout.bin: the kernels, no network
#
# The image is fifteen 2K banks and then the 2K fixed half (the layout the
# cartridge's vcs_set_image expects; MAME accepts 4K/8K/16K/32K only). The
# "FUJI" claim is stamped into the fixed half, or the cart treats the image
# as a plain game and the mailbox goes dead at boot.
#
# Env:
#   ENDPOINT=...       the server when no lobby appkey says
#                      (default http://fujinet.online:9900, the public server)
#   FUJI_FIRMWARE=...  the fn-2600 tree (default ~/Workspace/fn-2600)

set -euo pipefail
cd "$(dirname "$0")"

FUJI_FIRMWARE="${FUJI_FIRMWARE:-$HOME/Workspace/fn-2600}"
VCS="$FUJI_FIRMWARE/pico/atari-2600"

if command -v asl >/dev/null 2>&1; then
    AS=asl P2BIN=p2bin
elif [ -x "$HOME/asl/asl" ]; then
    AS="$HOME/asl/asl" P2BIN="$HOME/asl/p2bin"
else
    echo "build.sh: no Macroassembler AS found (tried PATH and ~/asl)" >&2
    exit 1
fi

mkdir -p build

# The mailbox equates are hand-mirrored from the firmware header: check them
# first, since a drifted address assembles, runs, and talks to nothing.
python3 "$VCS/tools/checkdefs.py" \
    "$VCS/firmware/include/fuji_mailbox.h" src/fujinet.inc \
    --extra "FB_TCELL=FN_BLIT_TCELL,FB_PATH=FN_BLIT_PATH,FB_TEXT=FN_BLIT_TEXT,FNBGEN=FN_B_BLITGEN,FH_BSL=FN_HOT_BLIT_SL,FH_BSH=FN_HOT_BLIT_SH,FH_BDL=FN_HOT_BLIT_DL,FH_BDH=FN_HOT_BLIT_DH,FH_BCNT=FN_HOT_BLIT_CNT,FH_BGO=FN_HOT_BLIT_GO,FP_POPCH=FN_PATH_POPCH,FP_SEL0=FN_PATH_SEL0,FP_SEL1=FN_PATH_SEL1,FP_SEL2=FN_PATH_SEL2,FP_SEL3=FN_PATH_SEL3,FP_SEED=FN_PATH_SEED,FP_COMMIT=FN_PATH_COMMIT,FNTROW=FN_T_ROWS,FNTCLH=FN_T_CELL_H,FB_MULEMAP=FN_BLIT_MULEMAP,MMPROD=FN_MULEMAP_PROD,FNMMAP0=FN_MULE_MAP0"

{
    echo "; generated by build.sh -- do not edit"
    printf 'UENDPT: DB      "%s"\n' "${ENDPOINT:-http://fujinet.online:9900}"
    echo "        DB      0"
} > build/endpoint.inc

bankfits() {
    python3 tools/checkbanks.py "build/$1.lst" "$2" "$1"
}

assemble() {
    local b=$1
    ( cd src && "$AS" -q -L -i . "$b.asm" )
    mv "src/$b.p" "build/$b.p"
    mv -f "src/$b.lst" "build/$b.lst" 2>/dev/null || true
}

stampclaim() {
    local f=$1 size
    size=$(stat -c%s "$f")
    printf 'FUJI' | dd of="$f" bs=1 \
        seek=$((size - 0x800 + 0x0710)) conv=notrunc status=none
    echo "$f: $size bytes"
}

# Bank order is bank number: mdefs.inc's BK* equates. A "-" is an unused
# bank, filled by stub.asm (back to the cold start).
python3 tools/mulemap.py --col build/mapcol.inc
python3 tools/mkgfx2600.py --atr mule.atr build/gen
python3 tools/mktown.py build/gen/town.inc
python3 tools/mkstr2600.py build/gen
BANKS="boot lobby net stat map dev town auction tables goods compose devx townx strpev strmsc"
OUT=mule2600
if [ "${1:-}" = "layout" ]; then
    # The kernels with no network: tables baked from tools/mulemap.py.
    python3 tools/mulemap.py --asm build/maptab.inc
    BANKS="maptest - - - - - - - - - - - - - -"
    OUT=layout
fi

# The tail first: the banks reach it through build/tail.inc, generated from
# the addresses it actually assembled to.
assemble mtail
python3 tools/mktail.py build/mtail.lst \
    FNRW,FNARM,FNCHK,FNBEG,FNPB,FNPW,FNLNCH,FNGO,FNACK,FNROWA,FNCHR,FNSPC \
    > build/tail.inc
tail -1 build/tail.inc | sed 's/^; */  tail: /'

parts=()
lsts=()
n=0
lastb=
for b in $BANKS; do
    [ "$b" = "-" ] && b=stub
    if [ ! -f "build/$b.bin" ] || [ $n -eq 0 ] || \
       { [ "$b" != stub ] && [ "$b" != phase ]; } || [ "$b" != "$lastb" ]; then
        assemble "$b"
        bankfits "$b" $((0x1800))
        "$P2BIN" "build/$b.p" "build/$b.bin" -r '$1000-$17FF' -l 0 >/dev/null
        rm -f "build/$b.p"
    fi
    parts+=("build/$b.bin")
    lsts+=("build/$b.lst")
    lastb=$b
    n=$((n + 1))
done

"$P2BIN" build/mtail.p build/mtail.bin -r '$1800-$1FFF' -l 0 >/dev/null
rm -f build/mtail.p

cat "${parts[@]}" build/mtail.bin > "build/$OUT.bin"
stampclaim "build/$OUT.bin"
# shellcheck disable=SC2046
python3 "$VCS/tools/checkrom.py" $(python3 tools/dataranges.py "${lsts[@]}") \
    "build/$OUT.bin"
