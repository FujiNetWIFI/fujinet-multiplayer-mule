#!/usr/bin/env python3
"""mktown.py -- the town, as the 2600's playfield draws it.

usage: mktown.py [--png out.png] OUT.inc

The Atari's town box is colour clocks 32-127 by 144 scanlines, a mode-4
picture with a colour per building. The 2600's playfield is 4 clocks a
pixel and one colour a scanline, so the town is redrawn rather than
converted: the buildings stand where the Atari's do (tools/extract's
manifest: 8x8 cells of 4 clocks by 8 lines), 4 playfield pixels wide: a
roof, its letter in white, a base -- the outfitters C S E F (crystite,
smithore, energy, food, left to right, as on the Atari), then the assay
office A, the land office L, the pub P, and the corral's fence. A row of
buildings shares its colours line by line.

Rows are ENTRIES of two scanlines (72), the same as the map kernel's, which
draws it: the town box is PF1 left (clocks 32-47, its low nibble), PF2 left,
PF0 right and PF1 right; PF0 left and PF2 right stay clear.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mulemap  # noqa: E402  (pixel_reg, the palette)

ENT = 72

LETTERS = {
    "C": ["####", "#...", "#...", "#...", "####"],
    "S": ["####", "#...", "####", "...#", "####"],
    "E": ["####", "#...", "###.", "#...", "####"],
    "F": ["####", "#...", "###.", "#...", "#..."],
    "A": [".##.", "#..#", "####", "#..#", "#..#"],
    "L": ["#...", "#...", "#...", "#...", "####"],
    "P": ["###.", "#..#", "###.", "#...", "#..."],
}

# (letter, first playfield pixel, top entry, entries tall); the town box's
# clock 32 is playfield pixel 8.
TOP = [("C", 9, 4, 16), ("S", 15, 4, 16), ("E", 21, 4, 16), ("F", 27, 4, 16)]
BOTTOM = [("A", 9, 36, 28), ("L", 14, 36, 24), ("P", 19, 36, 20)]
CORRAL = (25, 36, 6, 36)        # pixel, top, width, height

C_TOPROW = [0x1A, 0x18, 0x16]   # roof, body, base
C_BOTROW = [0xC6, 0xC4, 0xC2]
C_LETTER = 0x0E


def picture():
    """72 rows of 40 pixels, and a colour a row."""
    pix = [[0] * 40 for _ in range(ENT)]
    col = [0] * ENT

    def block(letter, px, top, h, cols):
        # roof 2 entries, the letter's 5 rows at 2 entries each (a hole in
        # the block), then the base to the bottom
        for e in range(top, top + h):
            k = e - top
            if k < 2:
                row, c = "####", cols[0]
            elif k < 12:
                row = LETTERS[letter][(k - 2) // 2]
                c = C_LETTER
            else:
                row, c = "####", cols[2]
            for b in range(4):
                if row[b] == "#":
                    pix[e][px + b] = 1
            col[e] = c

    for L, px, top, h in TOP:
        block(L, px, top, h, C_TOPROW)
    for L, px, top, h in BOTTOM:
        block(L, px, top, h, C_BOTROW)
    px, top, w, h = CORRAL
    for e in range(top, top + h):
        for b in range(w):
            if e in (top, top + h - 1) or b in (0, w - 1):
                pix[e][px + b] = 1
        if not col[e]:
            col[e] = C_BOTROW[1]
    return pix, col


def tables():
    pix, col = picture()
    t = [[0] * ENT for _ in range(6)]
    for e in range(ENT):
        for p in range(40):
            if pix[e][p]:
                r, m = mulemap.pixel_reg(p)
                t[r][e] |= m
    assert not any(t[0]) and not any(t[5]), "the town must stay in PF1L..PF1R"
    return t, col


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--png")
    ap.add_argument("out")
    a = ap.parse_args()
    t, col = tables()
    with open(a.out, "w") as f:
        f.write("; generated by tools/mktown.py -- do not edit\n")
        f.write("; each table at its devaddr.inc address: none crosses a page\n")
        for tab, org in ((t[1], "TWT1"), (t[2], "TWT2"), (t[3], "TWT3"), (t[4], "TWT4"),
                         (col, "TWCOL"), ([0] * ENT, "TWZERO")):
            f.write("        ORG     %s\n" % org)
            for k in range(0, ENT, 12):
                f.write("        DB      %s\n" % ",".join("$%02X" % b for b in tab[k:k + 12]))
    if a.png:
        from PIL import Image
        pal = mulemap.palette()
        pix, col = picture()
        img = Image.new("RGB", (160, ENT * 2))
        for y in range(ENT * 2):
            for x in range(160):
                img.putpixel((x, y), pal[col[y // 2]] if pix[y // 2][x // 4] else (0, 0, 0))
        img.resize((960, ENT * 6), Image.NEAREST).save(a.png)
    return 0


if __name__ == "__main__":
    sys.exit(main())
