#!/usr/bin/env python3
"""mkstr2600.py -- the long messages, in the Atari's wording, for banks 13/14.

usage: mkstr2600.py OUTDIR

The words come from the MekkoGX client's strings.c (clients/mekkogx/src),
which has them from the Atari; nothing here is retyped. A '%' is a number
(MNUM), a second '%' in a message the second number the bank works out, and
'@' the name of the player whose turn it is.

Output (AS, never committed):
  OUTDIR/strpev.inc  bank 13: player events 1-19 (the bank adds "*** "),
                     SPEV*
  OUTDIR/strmsc.inc  bank 14: the rest, by the message numbers below, and
                     player events 20-22 (27-29), SMSC*
Each file ends with its pointer tables (after DSTART: data, not code).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "mekkogx", "src", "strings.c")


def array(text, name):
    m = re.search(r"%s\[\]\s*=\s*\{(.*?)\};" % re.escape(name), text, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [s.encode().decode("unicode_escape") for s in re.findall(r'"((?:[^"\\]|\\.)*)"', body)]


def main():
    out = sys.argv[1]
    text = open(SRC).read()
    msgs = array(text, "msgs")
    pev = array(text, "pevents")
    rat = array(text, "ratings")

    def msg(s):
        return next(m for m in msgs if m.startswith(s))

    # bank 14's messages (the numbers mdefs.inc names, MS*)
    misc = [
        "",
        msg("YOU'RE LANDING"),
        msg("PRESS YOUR BUTTON TO SELECT"),
        msg("NO NEW PLOTS"),
        msg("THE COMPUTER IS TAKING"),
        "@" + msg("'S TURN"),
        msg("TIME HAS RUN OUT"),
        msg("PRESS ALL PLAYER"),
        msg("FOOD SHORTAGE"),
    ]
    ce = [msg(s) for s in ("PESTS RUIN", "PIRATES TAKE", "FOOD OUTPUT UP",
                           "MINING OUTPUT", "ENERGY OUTPUT", "A HUGE CRYSTITE",
                           "MULE GOES CRAZY", "ALL THE STOCK", "THE SHIP IS BACK")]
    misc += ce                                  # 9-17
    misc += [msg("BIDS START AT")]              # 18
    misc += ["OVERALL, " + r for r in rat]      # 19-25
    misc += [msg("THE SHIP WILL BE BACK")]      # 26
    misc += pev[19:]                            # 27-29: player events 20-22
    assert len(misc) == 30

    def emit(f, prefix, strs):
        for i, s in enumerate(strs):
            f.write('%s%d: DB "%s",0\n' % (prefix, i, s.replace('"', "'")))

    def ptrs(f, prefix, n):
        f.write("DSTART:\n")
        for part, op in (("L", "&$FF"), ("H", ">>8")):
            f.write("%s%s:\n" % (prefix, part))
            for k in range(0, n, 8):
                f.write("        DB      %s\n" % ",".join(
                    "(%s%d)%s" % (prefix, i, op) for i in range(k, min(n, k + 8))))

    with open(os.path.join(out, "strmsc.inc"), "w") as f:
        f.write("; generated by tools/mkstr2600.py -- do not edit\n")
        emit(f, "SMSC", misc)
    with open(os.path.join(out, "strmscp.inc"), "w") as f:
        f.write("; generated by tools/mkstr2600.py -- do not edit\n")
        ptrs(f, "SMSC", len(misc))
    with open(os.path.join(out, "strpev.inc"), "w") as f:
        f.write("; generated by tools/mkstr2600.py -- do not edit\n")
        emit(f, "SPEV", pev[:19])     # "*** " is added as it is expanded
    with open(os.path.join(out, "strpevp.inc"), "w") as f:
        f.write("; generated by tools/mkstr2600.py -- do not edit\n")
        ptrs(f, "SPEV", 19)
    return 0


if __name__ == "__main__":
    sys.exit(main())
