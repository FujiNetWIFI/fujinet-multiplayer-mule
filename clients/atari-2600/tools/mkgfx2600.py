#!/usr/bin/env python3
"""mkgfx2600.py -- the 2600's figures, from the Atari disk.

usage: mkgfx2600.py [--atr mule.atr] OUTDIR

The pictures come off the Atari M.U.L.E. disk through the Intellivision
client's extraction (clients/intv/tools/mkgfx.py): the same species frames,
map figures and M.U.L.E.s. Without a disk they fall back to its stand-in
art, and the first line of every output says so (a stand-in build looks
like lost work).

A 2600 player is 8 pixels wide, 1 bit a pixel, MSB left -- which is what the
Atari's player-missile shapes already are, so the bytes go across as they
are. The 2600 can mirror a player (REFPx), so only the right-facing frames
are kept. Rows are stored top first: the kernels index a shape with the
entry (or line) counting down the screen.

Output (AS, never committed):
  OUTDIR/mapspr.inc   the map's figures: 8 species x 7 frames x 8 rows
                      (walk right x2, stand, walk down x2, walk up x2);
                      the M.U.L.E., 2 frames x 8 rows; the wampus
  OUTDIR/aucspr.inc   the auction arena's: 8 species x (standing, a step)
  OUTDIR/townspr.inc  the town's: 8 species x 4 frames x 22 rows (walk
                      right x2, front, back); the M.U.L.E., 2 x 24
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "intv", "tools"))
import mkgfx as intv  # noqa: E402

# Map figure frames kept, from the Atari's 10 (0-1 walk right, 2-3 left,
# 4-5 standing, 6-7 down, 8-9 up).
MAP_FRAMES = (0, 1, 4, 6, 7, 8, 9)
# Town frames kept, from the 11 (0-1 walk right, 2-3 left, 4-7 front, 8-10
# back).
TOWN_FRAMES = (0, 1, 4, 8)


def to_bytes(rows):
    out = []
    for r in rows:
        v = 0
        for x in range(8):
            v = (v << 1) | (1 if r[x] else 0)
        out.append(v)
    return out


def emit(f, label, byts, per=8):
    f.write("%s:\n" % label)
    for k in range(0, len(byts), per):
        f.write("        DB      %s\n" % ",".join("$%02X" % b for b in byts[k:k + per]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--atr")
    ap.add_argument("outdir")
    a = ap.parse_args()
    atari = None
    if a.atr and os.path.exists(a.atr):
        atari = intv.Atari(a.atr)
    head = ("; generated by tools/mkgfx2600.py from %s -- do not edit\n"
            % ("the Atari disk" if atari else "STAND-IN ART (no mule.atr)"))
    if not atari:
        print("mkgfx2600: no mule.atr -- stand-in art", file=sys.stderr)

    os.makedirs(a.outdir, exist_ok=True)
    small = atari.map_species() if atari else {k: intv.map_species_fallback() for k in range(8)}
    if atari:
        mule = [to_bytes(atari.bytes_at(0x55AF, 8)), to_bytes(atari.bytes_at(0x55B7, 8))]
    else:
        mule = [to_bytes(intv.from_art(m)) for m in intv.MULE_ART]
    with open(os.path.join(a.outdir, "mapspr.inc"), "w") as f:
        f.write(head)
        f.write("; the map's figures: species * 56 + frame * 8\n")
        allb = []
        for sid in range(8):
            for fr in MAP_FRAMES:
                allb += to_bytes(small[sid][fr])
        emit(f, "MFIGS", allb)
        emit(f, "MMULE", mule[0] + mule[1])
        emit(f, "MWAMP", to_bytes(intv.from_art(intv.WAMPUS_ART)))
    with open(os.path.join(a.outdir, "aucspr.inc"), "w") as f:
        f.write(head)
        f.write("; the auction arena's: species * 16 + (0 standing, 8 a step)\n")
        ab = []
        for sid in range(8):
            ab += to_bytes(small[sid][4]) + to_bytes(small[sid][0])
        emit(f, "AFIGS", ab)

    big = atari.species() if atari else {k: intv.species_fallback(k) for k in range(8)}
    if atari:
        tm = [to_bytes(atari.bytes_at(0x54C0, 24)), to_bytes(atari.bytes_at(0x54D8, 24))]
    else:
        tm = [to_bytes(intv.pad(intv.from_art(m), 24)) for m in intv.MULE_ART]
    with open(os.path.join(a.outdir, "townspr.inc"), "w") as f:
        f.write(head)
        f.write("; the town's figures: species * 88 + frame * 22\n")
        allb = []
        for sid in range(8):
            for fr in TOWN_FRAMES:
                allb += to_bytes(big[sid][fr])
        emit(f, "TFIGS", allb)
        emit(f, "TMULE", tm[0] + tm[1])
    # The town kernel draws a row every two scanlines: every other row, the
    # Atari's height kept (11 and 12 rows).
    with open(os.path.join(a.outdir, "town2spr.inc"), "w") as f:
        f.write(head)
        # the M.U.L.E. first (devaddr.inc TWMULE, then TWFIGS right after)
        f.write("; the M.U.L.E., 2 frames x 12\n")
        m2 = []
        for m in tm:
            m2 += [m[i] | m[i + 1] for i in range(0, 24, 2)]
        emit(f, "TMUL2", m2)
        f.write("; the town's figures, every other row: species * 33 + frame * 11\n")
        f.write("; (walk right x2, front: walking up shows the front too)\n")
        allb = []
        for sid in range(8):
            for fr in TOWN_FRAMES[:3]:
                rows = to_bytes(big[sid][fr])
                allb += [rows[i] | rows[i + 1] for i in range(0, 22, 2)]
        emit(f, "TFIG2", allb)
    return 0


if __name__ == "__main__":
    sys.exit(main())
