#!/usr/bin/env python3
"""mkstrings.py -- the game's strings, from clients/mekkogx/src/strings.c.

The text stays identical to the other clients: this reads the C tables and
writes two string pages for zmac (gen/stra.inc: titles, messages, words,
goods, species; gen/strb.inc: player events, colony ratings), each a
pointer table per kind, then the NUL-terminated strings. The C macros for
key names get the Astrocade's keys.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "../../mekkogx/src/strings.c")

MACROS = {
    "KEY_END_NAME": '"="',
    "LOBBY_HINT": '"<> SPECIES   TRIGGER READY   C LEAVE"',
}


def tables(text):
    out = {}
    for name, body in re.findall(r"static const char \*const (\w+)\[\] = \{(.*?)\};", text, re.S):
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        for k, v in MACROS.items():
            body = body.replace(k, v)
        items = []
        # each entry: one or more adjacent "..." literals, then a comma
        for ent in re.findall(r'((?:"(?:[^"\\]|\\.)*"\s*)+),', body + ","):
            items.append("".join(re.findall(r'"((?:[^"\\]|\\.)*)"', ent)))
        out[name] = items
    return out


def db(s):
    s = s.upper()
    parts, cur = [], ""
    for ch in s:
        if ch == '"':
            if cur:
                parts.append('"%s"' % cur)
                cur = ""
            parts.append("22H")
        else:
            cur += ch
    if cur:
        parts.append('"%s"' % cur)
    parts.append("0")
    return "        DB      " + ",".join(parts)


def page(path, prefix, kinds, t):
    lines = ["; GENERATED by tools/mkstrings.py from mekkogx/src/strings.c -- do not edit"]
    for kind, lab in kinds:
        lines.append("%s:" % lab)
        items = t[kind]
        for i in range(0, len(items), 8):
            lines.append("        DW      " + ",".join("%s%d" % (lab, j) for j in range(i, min(i + 8, len(items)))))
    for kind, lab in kinds:
        for j, s in enumerate(t[kind]):
            lines.append("%s%d:" % (lab, j))
            lines.append(db(s))
    open(path, "w").write("\n".join(lines) + "\n")


def main():
    t = tables(open(SRC).read())
    need = ["titles", "msgs", "goods", "species", "words", "pevents", "ratings"]
    for n in need:
        if n not in t:
            sys.exit("mkstrings: no table " + n)
    os.makedirs("gen", exist_ok=True)
    page("gen/stra.inc", "A", [("titles", "STT"), ("msgs", "STM"), ("words", "STW"),
                               ("goods", "STG"), ("species", "STS")], t)
    page("gen/strb.inc", "B", [("pevents", "STP"), ("ratings", "STR")], t)
    print("mkstrings: %s" % ", ".join("%s %d" % (n, len(t[n])) for n in need))


if __name__ == "__main__":
    main()
