#!/usr/bin/env bash
# build.sh -- assemble the Astrocade M.U.L.E. client with zmac.
#
# Usage: ./build.sh
#
# Output: build/mule.bin, a banked APPBANK image (firmware protocol v2): the
# 8K window plus 4K pages, the mailbox pages clear, the "FUJI" claim at
# 0x1CFC so the mailbox stays alive when the image is booted over the
# network. tools/checkrom.py --banked enforces the layout; tools/checksize.py
# prints (and enforces) the per-region budgets, RAM included.
#
# Environment:
#   ENDPOINT=url        server when no lobby appkey says otherwise
#                       (default https://mule.fujinet.online)
#   AUTOPLAY=1          play by itself (soak tests)
#   ZMAC=path           assembler override
#
# The graphics come from the Atari disk (mule.atr, a symlink, never
# committed) through tools/mkgfx_astro.py into gen/; without the disk the
# generator falls back to stand-in art and says so loudly.

set -euo pipefail
cd "$(dirname "$0")"

CLAIM_OFF=$((0x1CFC))
FUJI_PICO=${FUJI_PICO:-$HOME/Workspace/fujinet-firmware/pico/astrocade}

# zmac 1.3 holds 2000 symbols; this program has more. The build compiles
# its own copy of the zmac 1.3 source with a bigger table (build/zmac),
# from ZMACSRC or the first tree below that has it.
find_zmacsrc() {
    local d
    for d in "${ZMACSRC:-}" "$HOME/Workspace/zmac-1.3" "$FUJI_PICO/tools/zmac"; do
        if [ -n "$d" ] && [ -f "$d/zmac.c" ] && [ -f "$d/mio.c" ]; then
            echo "$d"; return
        fi
    done
    echo "build.sh: no zmac 1.3 source found; set ZMACSRC=" >&2
    exit 1
}

mkdir -p build gen
if [ -n "${ZMAC:-}" ]; then
    :
elif [ -x build/zmac ]; then
    ZMAC=build/zmac
else
    src=$(find_zmacsrc)
    mkdir -p build/zmacsrc
    cp "$src"/*.c "$src"/*.h build/zmacsrc/
    sed -i 's/^#define ITEMTABLESIZE.*/#define ITEMTABLESIZE 16000/' build/zmacsrc/zmac.c
    (cd build/zmacsrc && gcc -O -o ../zmac zmac.c mio.c getoptn.c)
    ZMAC=build/zmac
fi

ENDPOINT=${ENDPOINT:-https://mule.fujinet.online}
{
    echo "; generated by build.sh -- do not edit"
    echo "AUTOPLAY EQU    ${AUTOPLAY:-0}"
} > build/flags.inc
{
    echo "; generated by build.sh -- do not edit"
    echo "UENDPT: DB      \"${ENDPOINT%/}\""
    echo "        DB      0"
} > build/endpoint.inc

if [ ! -f gen/stra.inc ] || [ tools/mkstrings.py -nt gen/stra.inc ]; then
    python3 tools/mkstrings.py
fi
if [ ! -f gen/gfx.inc ] || [ tools/mkgfx_astro.py -nt gen/gfx.inc ]; then
    python3 tools/mkgfx_astro.py
fi
head -3 gen/gfx.inc | grep -q "stand-in" && \
    echo "build.sh: WARNING: stand-in art (no mule.atr)" >&2

"$ZMAC" -o build/mule.raw -x build/mule.lst mule.asm

# The page count is the assembly's: NPAGES from the symbol table.
npages=$(sed -n '/^Symbol Table:/,$p' build/mule.lst \
         | grep -oiE '\bnpages\s+=\s*[0-9a-f]+' | grep -oE '[0-9a-fA-F]+$')
npages=$((16#$npages))
IMAGE=$((8192 + (npages - 2) * 4096))

size=$(wc -c < build/mule.raw)
if [ "$size" -gt "$IMAGE" ]; then
    echo "build.sh: mule is $size bytes, over the $IMAGE image" >&2
    exit 1
fi
{
    cat build/mule.raw
    head -c $((IMAGE - size)) /dev/zero
} > build/mule.bin
printf 'FUJI' | dd of=build/mule.bin bs=1 seek=$CLAIM_OFF \
    conv=notrunc status=none
rm -f build/mule.raw

python3 tools/checkrom.py --banked build/mule.bin
python3 tools/checksize.py build/mule.lst
python3 tools/checkcalls.py build/mule.lst
