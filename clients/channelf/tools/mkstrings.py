#!/usr/bin/env python3
"""mkstrings.py -- the game's strings, from clients/mekkogx/src/strings.c.

The wording stays the other clients'. This reads the C tables and writes
gen/str.inc for the data page (copied to RAM at boot): a DW pointer table
per kind, then the NUL-terminated strings. The C macros for key names get
the Channel F's controls: START ends, MODE leaves, the plunger is the button.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "../../mekkogx/src/strings.c")

MACROS = {
    "KEY_END_NAME": '"START"',
    "LEAVE_KEY_NAME": '"MODE"',
    "LOBBY_HINT": '"<> SPECIES  PUSH: READY  MODE: LEAVE"',
}

# Strings the Channel F's 24 columns need shorter, by (table, index): the
# summary's prompt gets one row (MSGONE), the lobby's status column 4 cells.
SHORT = {
    ("msgs", 10): "EVERYONE PUSH TO GO ON",     # M_PRESSALL
    ("words", 17): "CPU",                       # W_COMPUTER
}

KINDS = [("titles", "STT"), ("msgs", "STM"), ("words", "STW"), ("goods", "STG"),
         ("species", "STS"), ("pevents", "STP"), ("ratings", "STR")]


def tables(text):
    out = {}
    for name, body in re.findall(r"static const char \*const (\w+)\[\] = \{(.*?)\};", text, re.S):
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        for k, v in MACROS.items():
            body = body.replace(k, v)
        items = []
        for ent in re.findall(r'((?:"(?:[^"\\]|\\.)*"\s*)+),', body + ","):
            items.append("".join(re.findall(r'"((?:[^"\\]|\\.)*)"', ent)))
        out[name] = items
    return out


def db(s):
    s = s.upper()
    parts, cur = [], ""
    for ch in s:
        if ch in "\"'":
            if cur:
                parts.append('"%s"' % cur)
                cur = ""
            parts.append("%03XH" % ord(ch))
        else:
            cur += ch
    if cur:
        parts.append('"%s"' % cur)
    parts.append("0")
    return "        DB " + ",".join(parts)


def main():
    t = tables(open(SRC).read())
    for n, _ in KINDS:
        if n not in t:
            sys.exit("mkstrings: no table " + n)
    for (kind, j), v in SHORT.items():
        t[kind][j] = v
    os.makedirs("gen", exist_ok=True)
    L = ["; GENERATED by tools/mkstrings.py from mekkogx/src/strings.c -- do not edit"]
    for kind, lab in KINDS:
        items = t[kind]
        L.append("%s:" % lab)
        for i in range(0, len(items), 8):
            L.append("        DW " + ",".join("%s%d" % (lab, j) for j in range(i, min(i + 8, len(items)))))
    for kind, lab in KINDS:
        for j, s in enumerate(t[kind]):
            L.append("%s%d:" % (lab, j))
            L.append(db(s))
    open("gen/str.inc", "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
