#!/usr/bin/env bash
# build.sh -- assemble the Channel F M.U.L.E. client with Macroassembler AS.
#
# Usage: ./build.sh
#
# Output: build/mule.bin, a banked (APPBANK, cart protocol 2) image: the
# fixed 16K with the "FUJI" claim at $3FFC, then six 8K pages, 64K in all.
# tools/checkrom.py --banked checks the layout, tools/checksize.py the
# budgets, tools/checkcalls.py that no page calls into another,
# tools/checkacc.py that nothing reads A after PI/JMP/ENTER destroyed it.
#
# Environment:
#   ENDPOINT=url    the server when no lobby appkey says otherwise
#                   (default http://fujinet.online:9900)
#   AUTOPLAY=1      play by itself (soak tests)
#   DEBUG=1         extra checks (a wrong page traps)
#   ASL=, P2BIN=    the assembler (default ~/asl)
#
# The graphics come from the Atari disk (mule.atr, a symlink, never
# committed) through tools/mkgfx_chf.py; without it the generator falls
# back to stand-in art and says so.
set -euo pipefail
cd "$(dirname "$0")"

ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
[ -x "$ASL" ]   || { echo "build.sh: no assembler at $ASL" >&2; exit 1; }
[ -x "$P2BIN" ] || { echo "build.sh: no p2bin at $P2BIN" >&2; exit 1; }

mkdir -p build gen
ENDPOINT=${ENDPOINT:-http://fujinet.online:9900}
{
    echo "; generated by build.sh -- do not edit"
    echo "AUTOPLAY EQU ${AUTOPLAY:-0}"
    echo "DEBUG    EQU ${DEBUG:-0}"
    echo "GALTEST  EQU ${GALTEST:-0}"
    echo "FGFIRST  EQU ${FGFIRST:-0}"
    echo "FGCOUNT  EQU ${FGCOUNT:-8}"
} > build/flags.inc
{
    echo "; generated by build.sh -- do not edit"
    echo "UENDPT: DB \"${ENDPOINT%/}\",0"
} > build/endpoint.inc

python3 tools/mkfont.py gen/font.inc
for t in mkstrings mkgfx_chf; do
    [ -f tools/$t.py ] && python3 tools/$t.py
done
if [ -f gen/art.inc ] && head -1 gen/art.inc | grep -q "stand-in"; then
    echo "build.sh: WARNING: stand-in art (no mule.atr)" >&2
fi

"$ASL" mule.asm -L -i . -q -o build/mule.p -olist build/mule.lst
"$P2BIN" build/mule.p build/mule.bin -r 0x0000-0xffff -l 0xff -q
rm -f build/mule.p
python3 tools/checkrom.py build/mule.bin
[ -f tools/checksize.py ] && python3 tools/checksize.py build/mule.lst
[ -f tools/checkcalls.py ] && python3 tools/checkcalls.py build/mule.lst
python3 tools/checkacc.py src/*.inc mule.asm
exit 0
