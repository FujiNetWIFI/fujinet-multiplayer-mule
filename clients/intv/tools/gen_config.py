#!/usr/bin/env python3
"""Write gen/config.bas: the default server endpoint as a DATA string.
usage: gen_config.py <endpoint> gen/config.bas"""
import sys

url, out = sys.argv[1], sys.argv[2]
if '"' in url or len(url) > 63:
    sys.exit("endpoint must be under 64 characters and contain no quotes")
text = ("' config.bas -- GENERATED by tools/gen_config.py (make ENDPOINT=...).\n"
        "' The server used when the FujiNet lobby didn't pick one.\n"
        'lit_endpoint:\n    DATA %d, "%s"\n' % (len(url), url))
try:
    old = open(out).read()
except OSError:
    old = None
if old != text:            # only touch the file when the endpoint changes
    open(out, "w").write(text)
