#!/usr/bin/env python3
"""Generate IntyBASIC constants from clients/mule_proto.h.

usage: gen_proto.py ../mule_proto.h gen/proto.bas

The C header is generated from the server's Go structs, so it is the one
place the binary layout is written down. This script turns it into CONSTs
the Intellivision client can PEEK with:

  * every #define with a numeric value      -> CONST NAME = value
  * every struct field                      -> CONST S_<STRUCT>_<FIELD> = offset
                                               inside its struct
  * every field of MuleState                -> CONST ST_<PATH> = absolute offset
                                               (nested structs are flattened,
                                               e.g. ST_AUCTION_POS)
  * every struct size                       -> CONST SZ_<STRUCT> = size

Names are upper-cased; IntyBASIC folds case anyway.
"""
import re
import sys

TYPES = {"uint8_t": 1, "int8_t": 1, "char": 1, "uint16_t": 2, "int16_t": 2,
         "uint32_t": 4, "int32_t": 4}


def parse(text):
    defines = []
    for m in re.finditer(r"^#define\s+(\w+)\s+(0x[0-9A-Fa-f]+|-?\d+)\s*$", text, re.M):
        defines.append((m.group(1), int(m.group(2), 0)))
    structs = {}
    order = []
    for m in re.finditer(r"typedef struct\s*\{[^\n]*\n(.*?)\}\s*(\w+);", text, re.S):
        body, name = m.group(1), m.group(2)
        fields = []
        for line in body.splitlines():
            line = re.sub(r"/\*.*?\*/", "", line).strip()
            if not line:
                continue
            fm = re.match(r"(\w+)\s+(\w+)(?:\[(\d+)\])?;", line)
            if not fm:
                raise SystemExit("cannot parse field in %s: %r" % (name, line))
            typ, fname, count = fm.group(1), fm.group(2), int(fm.group(3) or 1)
            fields.append((typ, fname, count))
        structs[name] = fields
        order.append(name)
    return defines, structs, order


def size_of(structs, typ):
    if typ in TYPES:
        return TYPES[typ]
    return sum(size_of(structs, t) * c for t, _, c in structs[typ])


def snake(name):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).upper()


def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src).read()
    defines, structs, order = parse(text)
    out = ["' proto.bas -- GENERATED by tools/gen_proto.py from clients/mule_proto.h.",
           "' Do not edit; rerun `make proto` when the server's protocol changes.",
           ""]
    for name, val in defines:
        out.append("    CONST %s = %d" % (name, val))
    out.append("")
    for s in order:
        prefix = snake(s[4:] if s.startswith("Mule") else s)
        off = 0
        for typ, fname, count in structs[s]:
            out.append("    CONST S_%s_%s = %d" % (prefix, snake(fname), off))
            off += size_of(structs, typ) * count
        out.append("    CONST SZ_%s = %d" % (prefix, off))
        out.append("")

    # Absolute offsets inside MuleState.
    # The header fields are used so often that they get short names (ST_PHASE,
    # ST_T, ...); everything else is ST_<SUBSTRUCT>_<FIELD>.
    off = 0
    for ftyp, fname, count in structs["MuleState"]:
        if ftyp == "MuleHeader":
            o = off
            for htyp, hname, hc in structs["MuleHeader"]:
                out.append("    CONST ST_%s = %d" % (snake(hname), o))
                o += size_of(structs, htyp) * hc
        elif ftyp in structs and count == 1:
            o = off
            for styp, sname, sc in structs[ftyp]:
                out.append("    CONST ST_%s_%s = %d" % (snake(fname), snake(sname), o))
                o += size_of(structs, styp) * sc
        else:
            out.append("    CONST ST_%s = %d" % (snake(fname), off))
        off += size_of(structs, ftyp) * count
    out.append("    CONST SZ_STATE_TOTAL = %d" % off)
    out.append("")
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
