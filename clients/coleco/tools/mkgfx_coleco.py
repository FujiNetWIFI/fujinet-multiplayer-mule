#!/usr/bin/env python3
"""mkgfx_coleco.py -- the Adam's graphics, for zmac.

The art is the Coleco Adam client's: clients/mekkogx/tools/mkgfx_tms.py
makes it from the Atari disk (the Namco font, the plot parts, the shapes,
the town). This runs that generator into build/, reads its C tables back
and writes gen/gfx.inc. Without mule.atr the generator makes stand-in art
and says so; the first line of gen/gfx.inc then says "stand-in".

usage: mkgfx_coleco.py [--atr mule.atr]
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.dirname(HERE)
MKGFX = os.path.join(TOP, "../mekkogx/tools/mkgfx_tms.py")


def arrays(text):
    """name -> list of ints, for every `NAME[...] = { numbers };`."""
    out = {}
    for name, body in re.findall(r"(\w+)\s*(?:\[[^\]]*\])+\s*=\s*\{(.*?)\n\};", text, re.S):
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        if re.search(r"\b[A-Za-z_]\w*", re.sub(r"0x[0-9A-Fa-f]+", "", body)):
            continue                    # a table of pointers (the shapes)
        out[name] = [int(v, 0) for v in re.findall(r"0x[0-9A-Fa-f]+|\d+", body)]
    return out


def shapes(text):
    body = re.search(r"tms_shapes\[\d+\]\s*=\s*\{(.*?)\n\};", text, re.S).group(1)
    return re.findall(r"\{\s*(\w+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", body)


def db(lines, data, width=16):
    for i in range(0, len(data), width):
        lines.append("        DB      " + ",".join("%03XH" % v for v in data[i:i + width]))


def dw(lines, data, width=8):
    for i in range(0, len(data), width):
        lines.append("        DW      " + ",".join("%04XH" % v for v in data[i:i + width]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--atr")
    a = ap.parse_args()
    os.makedirs(os.path.join(TOP, "build"), exist_ok=True)
    os.makedirs(os.path.join(TOP, "gen"), exist_ok=True)
    cfile = os.path.join(TOP, "build", "tmsgfx.c")
    cmd = [sys.executable, MKGFX]
    if a.atr:
        cmd += ["--atr", a.atr]
    subprocess.run(cmd + [cfile], check=True)
    text = open(cfile).read()
    stand_in = not a.atr
    t = arrays(text)
    lines = ["; gfx.inc -- GENERATED by tools/mkgfx_coleco.py from the Adam's art%s; do not edit"
             % (" (stand-in: no mule.atr)" if stand_in else "")]
    lines.append("; the font: 64 characters from 20H, 8 bytes each, bit 7 left")
    lines.append("FONT:")
    db(lines, t["tms_font"])
    lines.append("; the plot parts: 32 lines x 3 bytes; border, icons 1-6, mountains 1-3, store, river")
    lines.append("PLPARTS:")
    db(lines, t["plot_parts"], 12)
    lines.append("; the production dots: line, pixel")
    lines.append("PLDOTS:")
    db(lines, t["plot_dots"])
    lines.append("; the small pictures: 8 x 8 clocks, a byte a row")
    lines.append("PICS:")
    db(lines, t["tms_pics"], 8)
    lines.append("; 8 colour clocks -> 12 pixels, bit 11 left")
    lines.append("WIDE12:")
    dw(lines, t["wide12"])
    lines.append("; the shapes: data, bytes a row, width (clocks), lines")
    lines.append("SHTAB:")
    for name, wb, w, h in shapes(text):
        lines.append("        DW      %s" % name.upper().replace("SH_", "SD_"))
        lines.append("        DB      %s,%s,%s" % (wb, w, h))
    for name, wb, w, h in shapes(text):
        lines.append("%s:" % name.upper().replace("SH_", "SD_"))
        db(lines, t[name])
    lines.append("; the pixels set in a byte: on a page of its own (POPC/256 is its high byte)")
    lines.append("        DS      (256-($ AND 255)) AND 255")
    lines.append("POPC:")
    db(lines, [bin(v).count("1") for v in range(256)])
    lines.append("; the town: 18 cell rows of 152 pattern then 152 colour bytes, packed")
    lines.append("TOWNRLE:")
    db(lines, t["town_rle"])
    open(os.path.join(TOP, "gen", "gfx.inc"), "w").write("\n".join(lines) + "\n")
    size = (len(t["tms_font"]) + len(t["plot_parts"]) + len(t["plot_dots"]) + len(t["tms_pics"])
            + 2 * len(t["wide12"]) + 5 * len(shapes(text)) + len(t["town_rle"])
            + sum(len(t[n]) for n, *_ in shapes(text)) + 256)
    print("mkgfx_coleco: %d bytes of art%s" % (size, " (STAND-IN)" if stand_in else ""))


if __name__ == "__main__":
    main()
