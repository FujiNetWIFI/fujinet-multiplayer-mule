#!/usr/bin/env bash
# build.sh -- assemble the ColecoVision M.U.L.E. client with zmac.
#
# Usage: ./build.sh
#
# Output: build/mule.rom, an APPBANK image for the FujiNet cartridge: the
# 32K window plus 8K pages, the mailbox pages clear, the "FUJI" claim at
# 7CFCH (tools/mkimage.py). tools/checksize.py prints (and enforces) the
# budgets, RAM included.
#
# Environment:
#   ENDPOINT=url        server when no lobby appkey says otherwise
#                       (default https://mule.fujinet.online)
#   AUTOPLAY=1          play by itself (soak tests)
#   ZMAC=path           assembler override
#
# The graphics are the Adam's (clients/mekkogx/tools/mkgfx_tms.py), from the
# Atari disk (mule.atr, a symlink, never committed); without it the
# generator falls back to stand-in art and the build says so.

set -euo pipefail
cd "$(dirname "$0")"

# zmac 1.3 holds 2000 symbols; this program has more. The build compiles
# its own copy with a bigger table (build/zmac).
find_zmacsrc() {
    local d
    for d in "${ZMACSRC:-}" "$HOME/Workspace/zmac-1.3" \
             "$HOME/Workspace/fujinet-firmware/pico/astrocade/tools/zmac"; do
        if [ -n "$d" ] && [ -f "$d/zmac.c" ] && [ -f "$d/mio.c" ]; then
            echo "$d"; return
        fi
    done
    echo "build.sh: no zmac 1.3 source found; set ZMACSRC=" >&2
    exit 1
}

mkdir -p build gen
if [ -n "${ZMAC:-}" ]; then
    :
elif [ -x build/zmac ]; then
    ZMAC=build/zmac
else
    src=$(find_zmacsrc)
    mkdir -p build/zmacsrc
    cp "$src"/*.c "$src"/*.h build/zmacsrc/
    sed -i 's/^#define ITEMTABLESIZE.*/#define ITEMTABLESIZE 16000/' build/zmacsrc/zmac.c
    (cd build/zmacsrc && gcc -O -o ../zmac zmac.c mio.c getoptn.c)
    ZMAC=build/zmac
fi

ENDPOINT=${ENDPOINT:-https://mule.fujinet.online}
{
    echo "; generated by build.sh -- do not edit"
    echo "AUTOPLAY EQU    ${AUTOPLAY:-0}"
} > build/flags.inc
{
    echo "; generated by build.sh -- do not edit"
    echo "UENDPT: DB      \"${ENDPOINT%/}\""
    echo "        DB      0"
} > build/endpoint.inc

if [ ! -f gen/stra.inc ] || [ tools/mkstrings.py -nt gen/stra.inc ]; then
    python3 tools/mkstrings.py
fi
if [ ! -f gen/gfx.inc ] || [ tools/mkgfx_coleco.py -nt gen/gfx.inc ]; then
    if [ -e mule.atr ]; then
        python3 tools/mkgfx_coleco.py --atr mule.atr
    else
        python3 tools/mkgfx_coleco.py
    fi
fi
head -1 gen/gfx.inc | grep -q "stand-in" && \
    echo "build.sh: WARNING: stand-in art (no mule.atr)" >&2

"$ZMAC" -o build/mule.raw -x build/mule.lst mule.asm
python3 tools/mkimage.py build/mule.raw build/mule.lst build/mule.rom
rm -f build/mule.raw
if [ -f tools/checksize.py ]; then
    python3 tools/checksize.py build/mule.lst
fi
