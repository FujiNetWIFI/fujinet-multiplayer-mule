#!/usr/bin/env python3
"""mkproto.py -- AS equates from clients/mule_proto.h, for the Studio II.

    mkproto.py ../mule_proto.h build/proto.inc

Every #define becomes an equate and every struct a set of field offsets
(<PRE>_<FIELD>, <PRE>_SIZE), as the O2's mkproto does. The cart copies each
state into its own RAM at SNAP ($D400), and the one before it to SNAP+PRVOFF,
so the fields also get their console addresses there:

  H_<F>   the header        MP_<F>  the map's arrays    SO_<F> the store
  G_<F>   the grant         A_<F>   the auction         TN_<F> the turn
  C_<F>   the colony        S_PLAYERS, seat k at S_PLAYERS + k*PL_SIZE

The layout is computed, never copied: a server change that moves a field
breaks the build instead of the game.
"""
import re
import sys

SNAP = 0xD400
PRVOFF = 0x300
SIZES = {"uint8_t": 1, "int8_t": 1, "char": 1, "uint16_t": 2, "int16_t": 2,
         "uint32_t": 4, "int32_t": 4}
PREFIX = {"MuleHeader": "HDR", "MulePlayer": "PL", "MuleMap": "MAP",
          "MuleStore": "STO", "MuleGrant": "GR", "MuleAuction": "AU",
          "MuleWampus": "WP", "MuleTurn": "TU", "MuleColony": "CO",
          "MuleState": "ST", "MuleTable": "TBL"}
ABS = {"h": "H", "map": "MP", "store": "SO", "grant": "G", "auction": "A",
       "turn": "TN", "colony": "C"}


def main(src, out):
    text = open(src).read()
    lines = ["; GENERATED by tools/mkproto.py from mule_proto.h -- do not edit."]
    for name, val in re.findall(r"^#define (\w+) ('.'|-?\d+|0x[0-9A-Fa-f]+)\s*$", text, re.M):
        if name == "MULE_PROTO_H":
            continue
        if val.startswith("0x"):
            val = "0%sH" % val[2:].upper()
        lines.append("%-24s EQU %s" % (name, val))

    sizes = dict(SIZES)
    fields = {}
    for body, sname in re.findall(r"typedef struct \{[^\n]*\n(.*?)\} (\w+);", text, re.S):
        pre = PREFIX[sname]
        off = 0
        fields[sname] = []
        for ftype, fname, count in re.findall(r"^\s*(\w+) (\w+)(?:\[(\d+)\])?;", body, re.M):
            n = int(count) if count else 1
            lines.append("%-24s EQU %d" % ("%s_%s" % (pre, fname.upper()), off))
            fields[sname].append((ftype, fname, off))
            off += sizes[ftype] * n
        sizes[sname] = off
        lines.append("%-24s EQU %d" % ("%s_SIZE" % pre, off))
    assert sizes["MuleState"] == 550, sizes["MuleState"]

    lines.append("SNAP                     EQU 0%04XH" % SNAP)
    lines.append("PRVOFF                   EQU 0%03XH" % PRVOFF)
    for ftype, member, off in fields["MuleState"]:
        if member == "players":
            lines.append("%-24s EQU 0%04XH" % ("S_PLAYERS", SNAP + off))
            continue
        pre = ABS[member]
        for _, fname, foff in fields[ftype]:
            lines.append("%-24s EQU 0%04XH" % ("%s_%s" % (pre, fname.upper()), SNAP + off + foff))
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
