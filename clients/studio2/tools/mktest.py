#!/usr/bin/env python3
"""mktest.py -- the offline test mode's fake state (mekkogx teststart.c).

usage: mktest.py mule_proto.h OUT.inc

Round 1 on a generated map, four players (seat 3 a computer), some land and
M.U.L.E.s, a turn, a goods auction: 550 bytes as the server sends them
(little-endian), which the test bank COPYs to SNAP and then patches for the
test's phase, argument and player event (src/test.inc).

TESTBIG=1: money, goods and scores as large as the fields must show.
"""
import os
import re
import struct
import sys

BIG = os.environ.get("TESTBIG") == "1"
SIZES = {"uint8_t": 1, "int8_t": 1, "char": 1, "uint16_t": 2, "int16_t": 2,
         "uint32_t": 4, "int32_t": 4}


def layouts(text):
    """{struct: {field: offset}} and sizes, from mule_proto.h."""
    sizes, offs = dict(SIZES), {}
    for body, sname in re.findall(r"typedef struct \{[^\n]*\n(.*?)\} (\w+);", text, re.S):
        off, f = 0, {}
        for ftype, fname, count in re.findall(r"^\s*(\w+) (\w+)(?:\[(\d+)\])?;", body, re.M):
            f[fname] = off
            off += sizes[ftype] * (int(count) if count else 1)
        sizes[sname], offs[sname] = off, f
    return offs, sizes


def state(offs, sizes):
    st = bytearray(550)

    def put(off, fmt, *v):
        struct.pack_into("<" + fmt, st, off, *v)

    top = offs["MuleState"]
    put(top["h"], "BBBBBbBBHHhh", ord("M"), 2, 1, 3, 1, 0, 0, 0, 0, 0, -1, 0)
    pl, psz = offs["MulePlayer"], sizes["MulePlayer"]
    for i in range(4):
        p = top["players"] + i * psz
        st[p:p + 3] = b"PL" + bytes([0x30 + i])
        st[p + pl["species"]] = (1 + i * 2) & 7
        st[p + pl["color"]] = i
        st[p + pl["flags"]] = 1 if i == 3 else 0
        put(p + pl["money"], "H", 1000)
        st[p + pl["goods"]] = 1 + i * 2
        put(p + pl["score"], "H", 5000 - i * 700)
        if BIG:
            put(p + pl["money"], "H", (12345, 987, 45678, 65535)[i])
            for g in range(4):
                st[p + pl["goods"] + g] = (250, 7, 120, 99)[(i + g) & 3]
            put(p + pl["score"], "H", (65000, 43210, 9999, 123)[i])
        st[p + pl["rank"]] = i + 1
        st[p + pl["prod"]] = 3 + i
        st[p + pl["spoil"]] = i
    mp = {k: top["map"] + v for k, v in offs["MuleMap"].items()}
    for p in range(45):
        c = 0
        if p % 9 == 4:
            c = 1
        if p == 22:
            c = 3
        if p % 9 == (p // 9) % 4:
            c = 2 + ((p // 9) % 3 + 1) * 4
        if p % 9 == 5 + (p // 9) % 4:
            c = 2 + ((p // 9 + 1) % 3 + 1) * 4
        st[mp["terrain"] + p] = c
        st[mp["owner"] + p] = 0xFF
        st[mp["mule"] + p] = 0xFF
        st[mp["crystite"] + p] = 0xFF
    for p, o, g, pr in ((10, 0, 0, 5), (12, 1, 1, 3), (30, 3, 1, 0), (20, 0, 2, 8), (14, 2, None, 0),
                        (34, 2, 3, 2)):
        st[mp["owner"] + p] = o
        if g is not None:
            st[mp["mule"] + p] = g
        st[mp["prod"] + p] = pr
    so = {k: top["store"] + v for k, v in offs["MuleStore"].items()}
    st[so["mules"]] = 14
    put(so["mulePrice"], "H", 100)
    for i in range(4):
        put(so["price"] + 2 * i, "H", 20 + i * 20)
        st[so["stock"] + i] = 8
    au = {k: top["auction"] + v for k, v in offs["MuleAuction"].items()}
    st[au["kind"]] = 2
    st[au["step"]] = 1
    put(au["storeBuy"], "H", 30)
    put(au["storeSell"], "H", 65)
    for i in range(4):
        st[au["role"] + i] = 1
        put(au["pos"] + 2 * i, "H", 20 + i * 5)
        put(au["target"] + 2 * i, "H", 40 + i * 5)
    st[au["role"] + 1] = 2
    st[au["ticks"]] = 70
    put(au["hi"], "H", 66)
    put(au["lo"], "H", 20)
    gr = {k: top["grant"] + v for k, v in offs["MuleGrant"].items()}
    st[gr["cursor"]] = 0xFF
    st[gr["step"]] = 12
    put(gr["next"], "H", 186 + 726)
    for i in range(4):
        st[gr["claimed"] + i] = 0xFF
    tu = {k: top["turn"] + v for k, v in offs["MuleTurn"].items()}
    st[tu["flags"]] = 1
    put(tu["length"], "H", 2828)
    put(tu["left"], "H", 2828)
    st[tu["pTU"]] = 28
    st[tu["carrying"]] = 0xFF
    st[tu["nWampus"]] = 1
    put(tu["wampus"] + offs["MuleWampus"]["to"], "H", 2815)   # plot 0, mount 0, from 0
    co = {k: top["colony"] + v for k, v in offs["MuleColony"].items()}
    st[co["plot"]] = 10
    st[co["rating"]] = 4
    put(co["total"], "I", 123456)
    return st


def main():
    src, dst = sys.argv[1], sys.argv[2]
    offs, sizes = layouts(open(src).read())
    st = state(offs, sizes)
    out = ["; GENERATED by tools/mktest.py -- do not edit.", "TSTST:"]
    for k in range(0, len(st), 16):
        out.append("        DB      " + ",".join("%03XH" % v for v in st[k:k + 16]))
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
