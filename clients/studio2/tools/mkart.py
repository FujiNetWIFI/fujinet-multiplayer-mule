#!/usr/bin/env python3
"""mkart.py -- art/*.txt to the cart's images.

usage: mkart.py ARTDIR OUTDIR

Each art file holds pictures drawn in '#' (lit) and '.' (dark):

    @IM_NAME            a picture: the rows follow, each a line of the image
    ##..
    .##.
    @IM_LEFT mirror IM_NAME   the same picture flipped left for right (the
                              cart's sprites have no flip)

Up to 8 pixels wide and 24 lines tall (the cart's IMAGE op). A name ending
in _MSK is the mask of the picture before it, for S2T_MASK (it must get the
next id: the cart takes id + 1). Ids are given in file order (files sorted
by name), so a picture's frames can be reached as IM_X + k.

A Studio II pixel is about three scanlines wide on a TV: draw each column
three rows' worth to look square.

Output:
  OUTDIR/art.inc      IM_NAME EQU id (and _W, _H)
  OUTDIR/artdata.inc  IMGTAB: id, width, height, rows... for every
                      picture, then $FF (gfx_load uploads it)
"""
import glob
import os
import sys

NIMAGES = 96


def parse(path):
    pics, cur = [], None
    for ln, line in enumerate(open(path), 1):
        line = line.rstrip()
        if not line or line.startswith("#!") or line.startswith(";"):
            continue
        if line.startswith("@"):
            w = line[1:].split()
            cur = (w[0], [], "%s:%d" % (path, ln))
            pics.append(cur)
            if len(w) == 3 and w[1] == "mirror":
                src = next((p for p in pics if p[0] == w[2]), None)
                if src is None:
                    sys.exit("mkart: %s:%d: no %s to mirror" % (path, ln, w[2]))
                width = max(len(r) for r in src[1])
                cur[1].extend(r.ljust(width, ".")[::-1] for r in src[1])
                cur = None
            continue
        if cur is None:
            sys.exit("mkart: %s:%d: rows before a @NAME" % (path, ln))
        if set(line) - set("#."):
            sys.exit("mkart: %s:%d: only '#' and '.' draw" % (path, ln))
        cur[1].append(line)
    return pics


def main():
    artdir, outdir = sys.argv[1], sys.argv[2]
    pics = []
    for path in sorted(glob.glob(os.path.join(artdir, "*.txt"))):
        pics += parse(path)
    if len(pics) > NIMAGES:
        sys.exit("mkart: %d pictures; the cart holds %d" % (len(pics), NIMAGES))
    names = [p[0] for p in pics]
    out = ["; GENERATED by tools/mkart.py from art/*.txt -- do not edit."]
    tab = ["IMGTAB:"]
    for i, (name, rows, where) in enumerate(pics):
        if names.count(name) > 1:
            sys.exit("mkart: %s: %s is drawn twice" % (where, name))
        if name.endswith("_MSK") and (i == 0 or names[i - 1] != name[:-4]):
            sys.exit("mkart: %s: the mask %s must follow %s" % (where, name, name[:-4]))
        w = max(len(r) for r in rows) if rows else 0
        if not 1 <= w <= 8 or not 1 <= len(rows) <= 24:
            sys.exit("mkart: %s: %s is %dx%d; 1-8 wide, 1-24 tall" % (where, name, w, len(rows)))
        out.append("%-20s EQU %d" % (name, i))
        out.append("%-20s EQU %d" % (name + "_W", w))
        out.append("%-20s EQU %d" % (name + "_H", len(rows)))
        data = [i, w, len(rows)]
        for r in rows:
            v = 0
            for k, c in enumerate(r):
                if c == "#":
                    v |= 0x80 >> k
            data.append(v)
        tab.append("        DB      " + ",".join("%03XH" % b for b in data))
    tab.append("        DB      0FFH")
    out.append("NIMG                 EQU %d" % len(pics))
    open(os.path.join(outdir, "art.inc"), "w").write("\n".join(out) + "\n")
    open(os.path.join(outdir, "artdata.inc"), "w").write("\n".join([out[0]] + tab) + "\n")
    print("mkart: %d pictures, %d bytes" % (len(pics), sum(3 + len(p[1]) for p in pics) + 1))


if __name__ == "__main__":
    main()
