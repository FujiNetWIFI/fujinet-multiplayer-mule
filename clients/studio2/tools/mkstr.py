#!/usr/bin/env python3
"""mkstr.py -- src/strings.txt to the strings banks.

usage: mkstr.py strings.txt OUTDIR

Each line of strings.txt is `NAME text`; blank lines and `#` comments are
skipped; `@bank` starts the next bank (a group indexed by arithmetic, such as
M_EVENT + n, must not straddle two). Text is printable ASCII (the cart's font has all of it); `%` is a
number, the first V1 and the second V2. Messages word-wrap at 16 columns, so
no word may be wider than that (a number counts 5).

A strings bank is data only: at $C400 the strings' addresses (high byte
first), then the strings, each ending in a NUL. str_get (fixed code) puts
the bank in, copies, and puts the caller's back.

Output:
  OUTDIR/strids.inc  NAME EQU id (bank STRBK + id / 64, entry id % 64)
  OUTDIR/str.inc     each bank inside IF BANK == STRBK + k
"""
import sys

PER_BANK = 64
BANK_BYTES = 0xC00              # $C400-$CFFF


def encode(name, text):
    nums = text.count("%")
    if nums > 2:
        sys.exit("mkstr: %s has more than two numbers" % name)
    for c in text:
        if not " " <= c <= "~":
            sys.exit("mkstr: %s: %r is not printable ASCII" % (name, c))
    for w in text.split(" "):
        if len(w.replace("%", "")) + 5 * w.count("%") > 16:
            sys.exit("mkstr: %s: the word %r is wider than a line" % (name, w))
    return list(text.encode("ascii")) + [0]


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    entries = []
    for line in open(src):
        line = line.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        name, _, text = line.strip().partition(" ")
        entries.append((name, text.strip()))
    banks = [[]]
    size = 0
    for name, text in entries:
        if name == "@bank":
            if banks[-1]:
                banks.append([])
                size = 0
            continue
        b = encode(name, text)
        if len(banks[-1]) == PER_BANK or size + len(b) > BANK_BYTES - 2 * PER_BANK:
            sys.exit("mkstr: bank %d is full at %s: add an @bank before its group"
                     % (len(banks) - 1, name))
        banks[-1].append((name, b))
        size += len(b)
    ids = ["; GENERATED by tools/mkstr.py from src/strings.txt -- do not edit.",
           "NSTRBK          EQU %d" % len(banks)]
    out = ["; GENERATED by tools/mkstr.py from src/strings.txt -- do not edit."]
    for k, bank in enumerate(banks):
        out.append("        IF      BANK == STRBK+%d" % k)
        out.append("        ORG     0C400H")
        for i, (name, b) in enumerate(bank):
            ids.append("%-16s EQU %d" % (name, k * PER_BANK + i))
            out.append("        DB      HI(STR_%s), LO(STR_%s)" % (name, name))
        for name, b in bank:
            out.append("STR_%s:" % name)
            for j in range(0, len(b), 16):
                out.append("        DB      " + ",".join("%03XH" % x for x in b[j:j + 16]))
        out.append("        ENDIF")
    open(outdir + "/str.inc", "w").write("\n".join(out) + "\n")
    open(outdir + "/strids.inc", "w").write("\n".join(ids) + "\n")
    print("mkstr: %d strings in %d banks (%s bytes)" % (
        sum(len(b) for b in banks), len(banks),
        "/".join(str(sum(len(x) + 2 for _, x in b)) for b in banks)))


if __name__ == "__main__":
    main()
