#!/usr/bin/env bash
# build.sh -- assemble M.U.L.E. for the RCA Studio II: build/mule.st2.
#
#   ENDPOINT=http://host:port   the server when no room appkey says (default
#                               http://fujinet.online:9900)
#   AUTOPLAY=1                  plays by itself (soak tests, films)
#   DEBUG=1                     the harness's extras
#
# The cart's protocol 2 (fujinet-firmware pico/studio2): fixed code in
# $0400-$BFFF, a bank window at $C400-$CFFF, cart RAM at $D400-$DFFF. Every
# bank is its own assembly of mule.asm (-D BANK=n), so a bank can call fixed
# code, and another bank only through bcall; tools/checkfixed.py checks that
# everything outside the window came out the same in all of them, and
# tools/mkst2.py builds the ST2: bank 0's whole image, then each bank's window.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
cd "$HERE"
OUT=build
ASL="${ASL:-$HOME/asl/asl}"
[ -x "$ASL" ] || ASL=$(command -v asl) || { echo "build.sh: no asl (Macroassembler AS)" >&2; exit 1; }
mkdir -p "$OUT"

ENDPOINT="${ENDPOINT:-http://fujinet.online:9900}"
ENDPOINT="${ENDPOINT%/}"
printf '; GENERATED by build.sh -- do not edit.\nUENDPT: DB "%s",0\n' "$ENDPOINT" > "$OUT/endpoint.inc"
printf '; GENERATED by build.sh -- do not edit.\nAUTOPLAY EQU %d\nDEBUG EQU %d\n' \
    "${AUTOPLAY:-0}" "${DEBUG:-0}" > "$OUT/flags.inc"

python3 tools/mkproto.py ../mule_proto.h "$OUT/proto.inc"
python3 tools/mkstr.py src/strings.txt "$OUT"
python3 tools/mkart.py art "$OUT"
python3 tools/mktest.py ../mule_proto.h "$OUT/teststate.inc"
NBANKS=$(sed -n 's/^NBANKS *EQU *\([0-9]*\).*/\1/p' src/equ.inc)

banks=()
for b in $(seq 0 $((NBANKS - 1))); do
    "$ASL" -q -L -U -D BANK=$b -i "$HERE/src" -i "$HERE/$OUT" \
        -o "$OUT/mule.b$b.p" -olist "$OUT/mule.b$b.lst" mule.asm
    python3 tools/checkrom.py "$OUT/mule.b$b.lst"
    [ "$b" = 0 ] || banks+=(--bank "$OUT/mule.b$b.p")
done
for b in $(seq 0 $((NBANKS - 1))); do python3 tools/fitcheck.py "$OUT/mule.b$b.lst"; done
python3 tools/checkfixed.py "$OUT"/mule.b*.p
python3 tools/checkldr.py src/*.inc
python3 tools/mkst2.py "$OUT/mule.b0.p" "$OUT/mule.st2" "M.U.L.E." "${banks[@]}"
