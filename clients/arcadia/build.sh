#!/usr/bin/env bash
# build.sh -- assemble M.U.L.E. for the Arcadia 2001: build/mule.bin.
#
#   ENDPOINT=http://host:port   the server when no room appkey says (default
#                               http://fujinet.online:9900)
#   AUTOPLAY=1                  plays by itself (soak tests, films)
#   DEBUG=1                     the harness's trace byte, the page checks
#
# Every page is its own assembly of mule.asm (PAGE EQU n), so a page can
# call fixed code but never another page; tools/mkmule.py checks that the
# fixed halves came out the same in all of them and builds the image: page
# 0's 8K (the mailbox empty, "FUJI" claimed), then pages 1.. (a protocol 2
# APPBANK image, fuji_mailbox.h).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
cd "$HERE"
OUT=build
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
mkdir -p "$OUT"

ENDPOINT="${ENDPOINT:-http://fujinet.online:9900}"
ENDPOINT="${ENDPOINT%/}"
printf '; GENERATED by build.sh -- do not edit.\nUENDPT: DB "%s",0\n' "$ENDPOINT" > "$OUT/endpoint.inc"
printf '; GENERATED by build.sh -- do not edit.\nAUTOPLAY EQU %d\nDEBUG EQU %d\n' \
    "${AUTOPLAY:-0}" "${DEBUG:-0}" > "$OUT/flags.inc"

python3 tools/mkproto.py ../mule_proto.h "$OUT/proto.inc"
NSTRPG=$(sed -n 's/^NSTRPG *EQU *\([0-9]*\).*/\1/p' src/pages.inc)
python3 tools/mkstr.py src/strings.txt "$OUT" "$NSTRPG"
python3 tools/mklogo.py art/logo.txt "$OUT/logo.inc" LOGO
python3 tools/mkart.py --atr mule.atr "$OUT"
python3 tools/mktest.py ../mule_proto.h "$OUT/teststate.inc"
NPAGES=$(python3 - <<'EOF'
import re
v = {}
for line in open("src/pages.inc"):
    m = re.match(r"(\w+)\s+EQU\s+([\w+]+)", line)
    if m and m.group(1) in ("STRPG", "NSTRPG", "NPAGES"):
        v[m.group(1)] = eval(m.group(2), {}, v)
print(v["NPAGES"])
EOF
)

for p in $(seq 0 $((NPAGES - 1))); do
    printf '; GENERATED by build.sh -- do not edit.\nPAGE EQU %d\n        INCLUDE "mule.asm"\n' "$p" \
        > "$OUT/mule_p$p.asm"
    "$ASL" -q -L -U -i "$HERE" -o "$OUT/mule_p$p.p" -olist "$OUT/mule_p$p.lst" "$OUT/mule_p$p.asm"
    "$P2BIN" "$OUT/mule_p$p.p" "$OUT/mule_p$p.flat" -r '$0000-$2FFF' -l 0 >/dev/null
done
python3 tools/mkmule.py "$OUT" "$NPAGES" "$OUT/mule.bin"
# the 2650's return stack is 8 deep and silently wraps: keep one spare
python3 tools/checkdepth.py --max 7 "$OUT"/mule_p*.lst
# a register read after a cart-RAM write (or another clobbering service)
python3 tools/checkclob.py src/*.inc
# a conditional branch testing a LODI's constant
python3 tools/checkcc.py src/*.inc
