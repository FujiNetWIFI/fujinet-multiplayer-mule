#!/usr/bin/env python3
"""mklogo.py -- art/logo.txt to the title's block-graphics cells.

usage: mklogo.py logo.txt OUT.inc LABEL

A block-graphics cell is 3 x 2 blocks: bits 2, 1, 0 the top row left to
right, 5, 4, 3 the bottom; bits 7-6 its ink (00 white, 01 cyan, 10
magenta, 11 blue). Emits LABEL: rows of 16 cells (DB), and LABELN EQU the
number of rows. A blank cell is $00: an exact $40 would end block
graphics on its row.
"""
import sys

INK = {"W": 0x00, "C": 0x40, "M": 0x80, "B": 0xC0}


def main():
    src, dst, label = sys.argv[1:4]
    rows = [l.rstrip("\n") for l in open(src) if l.strip() and not l.startswith("#")]
    if len(rows) % 2:
        rows.append("." * 48)
    out = ["; GENERATED by tools/mklogo.py from %s -- do not edit." % src, "%s:" % label]
    for r in range(0, len(rows), 2):
        top, bot = rows[r].ljust(48, "."), rows[r + 1].ljust(48, ".")
        cells = []
        for c in range(16):
            blocks = top[3 * c:3 * c + 3] + bot[3 * c:3 * c + 3]
            inks = {b for b in blocks if b != "."}
            if len(inks) > 1:
                sys.exit("mklogo: cell %d of row %d has two inks" % (c, r // 2))
            v = 0
            for k, b in enumerate(blocks):
                if b != ".":
                    v |= (4 >> k) if k < 3 else (0x20 >> (k - 3))
            if v:
                v |= INK[inks.pop()]
            cells.append(v)
        out.append("        DB      " + ",".join("$%02X" % v for v in cells))
    out.append("%sN EQU %d" % (label, len(rows) // 2))
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
