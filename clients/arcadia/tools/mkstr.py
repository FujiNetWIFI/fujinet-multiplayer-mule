#!/usr/bin/env python3
"""mkstr.py -- src/strings.txt to the strings pages.

usage: mkstr.py strings.txt OUTDIR NSTRPG

Each line of strings.txt is `NAME text`; blank lines and `#` comments are
skipped. The text is the Atari's wording in the 2637's font: A-Z, 0-9,
space and . , + $ / -- anything else stops the build (reword it). `%` is a
number: the first in a string is SAYV1 ($FE), the second SAYV2 ($FD). SAY
word-wraps at 16 columns, so no word may be wider than that (a number
counts 5).

Output:
  OUTDIR/strids.inc  NAME EQU id (id / 64 is the bank, so the page STRPG + id / 64)
  OUTDIR/str.inc     every bank, each inside IF PAGE == STRPG + k: its
                     strings' addresses (DWBE) at $0800, then the strings,
                     glyph codes ending in $FF
"""
import sys

GLYPH = {" ": 0x00, ".": 0x34, ",": 0x35, "+": 0x36, "$": 0x37, "/": 0x01}
for i, c in enumerate("0123456789"):
    GLYPH[c] = 0x10 + i
for i, c in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZ"):
    GLYPH[c] = 0x1A + i
PER_BANK = 64
PAGE_BYTES = 2047               # $0800-$0FFE ($0FFF is the page's id)


def encode(name, text):
    out = []
    nums = 0
    for c in text:
        if c == "%":
            out.append(0xFE if nums == 0 else 0xFD)
            nums += 1
            if nums > 2:
                sys.exit("mkstr: %s has more than two numbers" % name)
        elif c in GLYPH:
            out.append(GLYPH[c])
        else:
            sys.exit("mkstr: %s: %r is not in the Arcadia's font: %s" % (name, c, text))
    for w in text.split(" "):
        width = len(w.replace("%", "")) + 5 * w.count("%")
        if width > 16:
            sys.exit("mkstr: %s: the word %r is wider than a line" % (name, w))
    out.append(0xFF)
    return out


def main():
    src, outdir, nbanks = sys.argv[1], sys.argv[2], int(sys.argv[3])
    entries = []
    for ln, line in enumerate(open(src), 1):
        line = line.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        name, _, text = line.strip().partition(" ")
        entries.append((name, text.strip()))
    banks = [[]]
    size = 0
    for name, text in entries:
        b = encode(name, text)
        if len(banks[-1]) == PER_BANK or size + 2 * (len(banks[-1]) + 1) + len(b) > PAGE_BYTES - 2 * PER_BANK:
            banks.append([])
            size = 0
        banks[-1].append((name, b))
        size += len(b)
    if len(banks) > nbanks:
        sys.exit("mkstr: %d banks of strings, %d pages for them" % (len(banks), nbanks))
    ids = []
    out = ["; GENERATED by tools/mkstr.py from src/strings.txt -- do not edit."]
    for k, bank in enumerate(banks):
        out.append("        IF      PAGE == STRPG+%d" % k)
        for i, (name, b) in enumerate(bank):
            ids.append("%-16s EQU %d" % (name, k * PER_BANK + i))
            out.append("        DWBE    STR_%s" % name)
        for name, b in bank:
            out.append("STR_%s:" % name)
            for j in range(0, len(b), 16):
                out.append("        DB      " + ",".join("$%02X" % x for x in b[j:j + 16]))
        out.append("        ENDIF")
    open(outdir + "/str.inc", "w").write("\n".join(out) + "\n")
    open(outdir + "/strids.inc", "w").write("; GENERATED by tools/mkstr.py -- do not edit.\n" + "\n".join(ids) + "\n")
    print("mkstr: %d strings in %d banks" % (len(entries), len(banks)))


if __name__ == "__main__":
    main()
