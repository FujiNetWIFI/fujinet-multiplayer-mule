#!/usr/bin/env python3
"""mkart.py -- the Arcadia's pictures, from the Atari disk.

usage: mkart.py [--atr mule.atr] OUTDIR [--preview DIR]

The art page (PG_ART) holds every 8x8 bitmap the game loads into a user
glyph -- a sprite's picture or a background glyph -- one byte a row, bit 7
the leftmost pixel. Sprites usually show them doubled (8 x 16).

The pictures come off the Atari M.U.L.E. disk through the Intellivision
client's extraction (clients/intv/tools/mkgfx.py) and MekkoGX's shapes
(clients/mekkogx/tools/mkgfx_hgr.py); without a disk, their stand-in art,
and the first line of every output says so.

Output (never committed):
  OUTDIR/artequ.inc  ART_* EQU address (every page's assembly includes it:
                     fixed code and the pages queue loads by address)
  OUTDIR/art.inc     the data, in that order (the art page includes it)
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "intv", "tools"))
sys.path.insert(0, os.path.join(HERE, "..", "..", "mekkogx", "tools"))
import mkgfx as intv            # noqa: E402
import mkgfx_hgr as hgr         # noqa: E402

BASE = 0x0800


def rows8(rows, w=8):
    """A list of pixel rows (lists of 0/1) to bytes, 8 wide, MSB left."""
    out = []
    for r in rows:
        v = 0
        for x in range(8):
            v = (v << 1) | (1 if x < len(r) and r[x] else 0)
        out.append(v)
    return out


def art(lines):
    return rows8(intv.from_art(lines))


def fit8(rows):
    """Any height to 8 rows: shorter is padded at the bottom, taller is
    squeezed by OR-ing neighbouring rows together."""
    n = len(rows)
    if n <= 8:
        return rows8(rows) + [0] * (8 - n)
    out = []
    for k in range(8):
        a, b = k * n // 8, max(k * n // 8 + 1, (k + 1) * n // 8)
        v = 0
        for r in rows[a:b]:
            v |= rows8([r])[0]
        out.append(v)
    return out


def mirror(b):
    return [int("{:08b}".format(v)[::-1], 2) for v in b]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--atr")
    ap.add_argument("--preview")
    ap.add_argument("outdir")
    a = ap.parse_args()
    atari = None
    if a.atr and os.path.exists(a.atr):
        atari = intv.Atari(a.atr)
    else:
        print("mkart: no mule.atr -- STAND-IN ART", file=sys.stderr)
    head = "; GENERATED by tools/mkart.py from %s -- do not edit.\n" % (
        "the Atari disk" if atari else "STAND-IN ART (no mule.atr)")

    items = []          # (label, [bytes], comment)

    # the species, small (the Atari's map figures): 10 frames each --
    # 0-1 walk right, 2-3 walk left, 4-5 stand, 6-7 walk down, 8-9 walk up
    small = atari.map_species() if atari else {k: intv.map_species_fallback() for k in range(8)}
    figs = []
    for sid in range(8):
        for f in range(10):
            figs += fit8(small[sid][f])
    items.append(("ART_FIG", figs, "8 species x 10 frames: right 0-1, left 2-3, stand 4-5, down 6-7, up 8-9"))

    # the M.U.L.E.: right 2 frames, left 2 frames
    if atari:
        mule = [rows8(atari.bytes_at(0x55AF, 8)), rows8(atari.bytes_at(0x55B7, 8))]
    else:
        mule = [art(m) for m in intv.MULE_ART]
    items.append(("ART_MULE", mule[0] + mule[1] + mirror(mule[0]) + mirror(mule[1]),
                  "the M.U.L.E.: right x2, left x2"))
    items.append(("ART_WAMP", art(intv.WAMPUS_ART), "the wampus"))
    items.append(("ART_CURS", [0xFF] + [0x81] * 6 + [0xFF], "the grant cursor: a plot's outline (doubled)"))

    # ships: four sprites side by side, drawn for the Arcadia (art/ships.txt)
    shipart = {}
    name = None
    for line in open(os.path.join(HERE, "..", "art", "ships.txt")):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        if not set(line) <= set(".X"):
            name = line
            shipart[name] = []
        else:
            shipart[name].append(line)
    for k, (key, label) in enumerate((("transport", "ART_TSHIP"), ("pirate", "ART_PSHIP"))):
        rows = intv.from_art(shipart[key], 32)
        parts = []
        for x in (0, 8, 16, 24):
            parts += rows8([r[x:x + 8] for r in rows])
        items.append((label, parts, "the %s ship: 4 slices left to right" % key))
    shapes = {s.name: s for s in hgr.shapes(atari)}
    items.append(("ART_DOCK", sum((fit8(f) for f in shapes["dock"].frames), []), "docking: 4 frames"))
    items.append(("ART_PEST", sum((fit8(f) for f in shapes["pest"].frames), []), "the pest: 4 frames"))
    clouds = []
    for f in shapes["cloud"].frames:     # 16 wide, 28 tall: its left half, squeezed
        clouds += fit8([r[0:16:2] for r in f])
    items.append(("ART_CLOUD", clouds, "the acid rain cloud: 4 frames"))
    items.append(("ART_BOLT", fit8(shapes["bolt"].frames[0]), "lightning"))
    items.append(("ART_SPARK", [0x18, 0x18, 0, 0, 0, 0, 0, 0], "a sunspot spark"))
    items.append(("ART_METEOR", art(intv.METEOR_ART), "the meteorite"))
    items.append(("ART_FIRE", art(intv.FIRE_ART[0]) + art(intv.FIRE_ART[1]), "fire: 2 frames"))
    items.append(("ART_CRATER", art(["........", "........", "........", "..XXXX..", ".X....X.",
                                     "X.XXXX.X", ".XXXXXX.", "........"]), "a crater"))

    # background glyphs: the map's
    for m in (1, 2, 3):
        items.append(("ART_PEAK%d" % m, art(intv.INTY_MOUNTAINS[m]), "%d mountains" % m))
    river = intv.from_art(intv.RIVER_ART)
    rv = []
    for ph in range(4):                  # it flows: four phases, two rows apart
        rv += rows8([river[(y + 14 - 4 * ph) % 16] for y in range(0, 16, 2)])
    items.append(("ART_RIVER", rv, "the river: 4 phases"))
    items.append(("ART_STORE", rows8([r[0:16:2] for r in intv.from_art(intv.STORE_ART, 16)[0:16:2]]),
                  "the store"))

    addr = BASE
    equ, data = [head], [head]
    for label, b, comment in items:
        equ.append("%-12s EQU $%04X     ; %s (%d bytes)" % (label, addr, comment, len(b)))
        data.append("; %s" % comment)
        data.append("        IF      $ <> %s" % label)
        data.append('        ERROR   "art.inc out of step with artequ.inc at %s"' % label)
        data.append("        ENDIF")
        for k in range(0, len(b), 8):
            data.append("        DB      " + ",".join("$%02X" % v for v in b[k:k + 8]))
        addr += len(b)
    equ.append("ART_END      EQU $%04X" % addr)
    if addr > 0x0FFF:
        sys.exit("mkart: %d bytes of art, past the page" % (addr - BASE))
    os.makedirs(a.outdir, exist_ok=True)
    open(os.path.join(a.outdir, "artequ.inc"), "w").write("\n".join(equ) + "\n")
    open(os.path.join(a.outdir, "art.inc"), "w").write("\n".join(data) + "\n")
    print("mkart: %d bytes of art%s" % (addr - BASE, "" if atari else " (STAND-IN)"))
    if a.preview:
        from PIL import Image
        os.makedirs(a.preview, exist_ok=True)
        allb = [v for _, b, _ in items for v in b]
        n = len(allb) // 8
        img = Image.new("L", (16 * 9, ((n + 15) // 16) * 9), 40)
        for i in range(n):
            for y in range(8):
                for x in range(8):
                    if allb[i * 8 + y] & (0x80 >> x):
                        img.putpixel(((i % 16) * 9 + x, (i // 16) * 9 + y), 255)
        img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(os.path.join(a.preview, "art.png"))


if __name__ == "__main__":
    main()
