#!/usr/bin/env python3
"""mkproto.py -- clients/mule_proto.h to AS equates for the Arcadia client.

usage: mkproto.py mule_proto.h OUT.inc

The 550-byte MuleState is never kept whole: the client copies the parts it
draws into cart RAM (see src/ram.inc), most of it into RAM-L ($0600-$07FF,
which page-0 code reads by name) and the wampus list into RAM-H. This
writes:
  - every #define as NAME EQU value;
  - S_<STRUCT>_<FIELD> EQU offset within the state (all of them, by the
    struct layout), and SZ_<STRUCT>;
  - H_<FIELD> EQU the console address of each copied field (H_ for the
    header, PL_ offsets within a 29-byte player, H_PLAYERS the first);
  - the ingest table INGTAB: per run, the state offset (hi, lo), the
    length, the cart RAM address (hi 0-3, lo), ending in $FF.
Multi-byte fields are big-endian: the client asks for ?be=1.
"""
import re
import sys

SIZES = {"uint8_t": 1, "int8_t": 1, "char": 1, "uint16_t": 2, "int16_t": 2,
         "uint32_t": 4, "int32_t": 4}

# What is copied, in state order: (first state offset, length, where).
# RAM-L is cart address 0x000-0x1FF (console $0600), RAM-H 0x200-0x3FF
# ($2900). The map's crystite (the assay results, never drawn) and the
# padding are left out. The header goes to a staging slot first (HSTAGE)
# and is committed last, so a phase change is never half in.
RAML, RAMH = 0x000, 0x200
HSTAGE = RAMH + 0x1F0          # 16 bytes at $2AF0


def parse(path):
    text = open(path).read()
    defines = []
    for m in re.finditer(r"^#define\s+(\w+)\s+(\S+)", text, re.M):
        name, val = m.groups()
        if name in ("MULE_PROTO_H",):
            continue
        if val.startswith("'") and val.endswith("'") and len(val) == 3:
            val = str(ord(val[1]))
        try:
            int(val, 0)
        except ValueError:
            continue
        if val.lower().startswith("0x"):
            val = "$" + val[2:]
        defines.append((name, val))
    structs = {}
    order = []
    for m in re.finditer(r"typedef struct \{[^\n]*\n(.*?)\}\s*(\w+);", text, re.S):
        body, name = m.groups()
        fields = []
        for line in body.split("\n"):
            line = line.split("/*")[0].strip()
            fm = re.match(r"(\w+)\s+(\w+)(?:\[(\d+)\])?;", line)
            if not fm:
                continue
            typ, fname, count = fm.groups()
            fields.append((typ, fname, int(count) if count else 1))
        structs[name] = fields
        order.append(name)
    return defines, structs, order


def size_of(structs, typ):
    if typ in SIZES:
        return SIZES[typ]
    return sum(size_of(structs, t) * n for t, _, n in structs[typ])


def layout(structs, typ, base=0, prefix=""):
    out = []
    off = base
    for t, f, n in structs[typ]:
        out.append((prefix + f, off, t, n))
        off += size_of(structs, t) * n
    return out


def main():
    src, dst = sys.argv[1], sys.argv[2]
    defines, structs, order = parse(src)
    assert size_of(structs, "MuleState") == 550, "MuleState is not 550 bytes"
    lines = ["; GENERATED by tools/mkproto.py from clients/mule_proto.h -- do not edit."]
    for n, v in defines:
        lines.append("%-16s EQU %s" % (n, v))
    for s in order:
        lines.append("SZ_%-13s EQU %d" % (s.upper(), size_of(structs, s)))
        for f, off, t, n in layout(structs, s):
            lines.append("S_%-14s EQU %d" % ((s[4:] if s.startswith("Mule") else s).upper() + "_" + f.upper(), off))
    # where each top-level section starts in the state
    top = {f: off for f, off, t, n in layout(structs, "MuleState")}
    mp = {f: off for f, off, t, n in layout(structs, "MuleMap", top["map"])}
    turn = {f: off for f, off, t, n in layout(structs, "MuleTurn", top["turn"])}
    wl = 12 * size_of(structs, "MuleWampus")
    cl = size_of(structs, "MuleColony")
    # (state offset, length, cart address), in state order: the reply is
    # read a 256-byte slice at a time, so this order switches slices least
    a1 = RAML + 16
    a2 = a1 + (mp["crystite"] - 16)
    a3 = a2 + (turn["wampus"] - mp["prod"])
    placed = [
        (16, mp["crystite"] - 16, a1),                      # players, terrain/owner/mule
        (mp["prod"], turn["wampus"] - mp["prod"], a2),      # prod, store, grant, auction, turn head
        (turn["wampus"], wl, RAMH),                         # the wampus list
        (top["colony"], cl, a3),                            # colony
        (0, 16, HSTAGE),    # the header, staged last: an error reply copies only it
    ]
    cart = a3 + cl
    assert cart <= RAMH, "RAM-L overflows: %d" % cart
    # console address of state offset o (the header: where it is committed)
    def addr(o):
        if o < 16:
            return 0x0600 + o
        for so, ln, ca in placed[:-1]:
            if so <= o < so + ln:
                ca += o - so
                return (0x0600 + ca) if ca < RAMH else (0x2900 + ca - RAMH)
        return None
    lines.append("; ---- the copy in cart RAM (console addresses) ----")
    for s, fieldbase in (("MuleHeader", 0), ("MuleMap", top["map"]), ("MuleStore", top["store"]),
                         ("MuleGrant", top["grant"]), ("MuleAuction", top["auction"]),
                         ("MuleTurn", top["turn"]), ("MuleColony", top["colony"])):
        pre = {"MuleHeader": "H_", "MuleMap": "MP_", "MuleStore": "ST_", "MuleGrant": "G_",
               "MuleAuction": "A_", "MuleTurn": "TN_", "MuleColony": "C_"}[s]
        for f, off, t, n in layout(structs, s, fieldbase):
            a = addr(off)
            if a is not None:
                lines.append("%-16s EQU $%04X" % (pre + f.upper(), a))
    lines.append("H_PLAYERS        EQU $%04X" % addr(top["players"]))
    for f, off, t, n in layout(structs, "MulePlayer"):
        lines.append("PL_%-13s EQU %d" % (f.upper(), off))
    lines.append("CR_LEND          EQU $%04X  ; first free RAM-L byte" % (0x0600 + cart))
    lines.append("CR_HSTAGE        EQU $%04X" % (0x2900 + HSTAGE - RAMH))
    lines.append("INGHDR           EQU %d     ; the header's run, x5" % (5 * (len(placed) - 1)))
    lines.append("; the ingest runs: state offset hi, lo, length, cart address hi, lo")
    lines.append("INGTAB  MACRO")
    for so, ln, ca in placed:
        lines.append("        DB      $%02X,$%02X,%d,%d,$%02X" % (so >> 8, so & 0xFF, ln, ca >> 8, ca & 0xFF))
    lines.append("        DB      $FF")
    lines.append("        ENDM")
    open(dst, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
